# static/ is published as it stands, at the top of the site: static/robots.txt
# is served as /robots.txt. Nothing here decides what goes out, which is the
# point of the directory - dropping a file in it is the whole of adding one.
cp -R static/. "$OUT/"

# Everything in articles/ that is not an article: the images, the video, the
# stylesheets the legacy pages link to relatively, and those pages themselves.
# Copied rather than content-addressed because an article body names its media
# by the plain filename sitting beside it.
#
# A stylesheet that already went out under a content hash is skipped, so that
# the one an article links to is the only copy published. articles/styles.css
# stays: no article names it, but the old copy of the tour sitting in there
# links to it by that name.
for f in articles/*; do
  [ -f "$f" ] || continue
  case "$f" in
    *.md)  if has_frontmatter "$f"; then continue; fi
           echo "build.sh: $f has no front matter, publishing it as raw markdown" ;;
    *.css) if cut -f1 "$CSS_MANIFEST" | grep -qxF "$f"; then continue; fi ;;
  esac
  cp "$f" "$OUT/$f"
done

echo "build.sh: wrote $OUT"
