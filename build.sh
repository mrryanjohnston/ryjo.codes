    if(p > 1) rb_put(cls, item, substr(txt, 1, p - 1))
    rb_shut(); rbout = rbout "\n"
    txt = substr(txt, p + 1) }
  if(txt != "") rb_put(cls, item, txt) }

function rb_kwchar(ch){ return ch != "" && ch ~ /[0-9A-Za-z_]/ }

function rb_eol(s, i,   p){ p = index(substr(s, i), "\n"); return p == 0 ? length(s) + 1 : i + p - 1 }

# rb_ctext(): what a comment holds, with the words that file picks out of it.
function rb_ctext(item, txt,   i, n, p, ch, w, run){
  n = length(txt); i = 1; run = ""
  while(i <= n){
    ch = substr(txt, i, 1)
    if(ch ~ /[A-Za-z_]/ && !rb_kwchar(i > 1 ? substr(txt, i - 1, 1) : "")){
      p = i
      while(rb_kwchar(substr(txt, p, 1))) p++
      w = substr(txt, i, p - i)
      if(w in RBTODO){
        rb_lines("Comment", item, run); run = ""
        rb_put("Todo", "todo", w) }
      else run = run w
      i = p; continue }
    run = run ch; i++ }
  rb_lines("Comment", item, run) }

# rb_back(): the last character before i that is not a space or a tab, or "" at
# the head of a line - which is how that file decides whether a slash opens a
# regular expression and whether an if opens a block or trails a statement.
function rb_back(s, i,   j, ch){
  for(j = i - 1; j >= 1; j--){
    ch = substr(s, j, 1)
    if(ch == "\n") return ""
    if(ch != " " && ch != "\t") return ch }
  return "" }

# rb_backword(): the word ending just before i, or "".
function rb_backword(s, i,   j, k, ch){
  j = i - 1
  while(j >= 1 && (substr(s, j, 1) == " " || substr(s, j, 1) == "\t")) j--
  k = j
  while(k >= 1 && rb_kwchar(substr(s, k, 1))) k--
  return k < j ? substr(s, k + 1, j - k) : "" }

# rb_value(): whether a value may begin at i, which is where a slash is the
# start of a regular expression and not a division.
function rb_value(s, i,   ch, w){
  ch = rb_back(s, i)
  if(ch == "") return 1
  if(index(";~=!|&(,{[<>?:*+-", ch) > 0) return 1
  w = rb_backword(s, i)
  return (w in RBVALUE)
}

# rb_open(), rb_close(): the stack that pairs an end with the word it closes.
function rb_open(kind, word, at){
  rbstack[++rbdepth] = kind; rbstackword[rbdepth] = word; rbstackat[rbdepth] = at }
function rb_close(   kind){
  if(rbdepth == 0) return "stmt"
  kind = rbstack[rbdepth--]
  return kind }

# rb_escape(): the length of the backslash escape at i, and RBESC with the item
# that file reads it as, so that two of them side by side stay two spans.
function rb_escape(s, i,   ch, j, d){
  ch = substr(s, i + 1, 1)
  RBESC = "esc"
  if(ch == "") return 1
  if(ch ~ /[0-7]/){
    j = i + 1; d = 0
    while(d < 3 && substr(s, j + 1, 1) ~ /[0-7]/){ j++; d++ }
    return j - i + 1 }
  if(ch == "x"){
    j = i + 2; d = 0
    while(d < 2 && substr(s, j, 1) ~ /[0-9a-fA-F]/){ j++; d++ }
    if(d > 0) return j - i }
  if(ch == "u"){
    if(substr(s, i + 2, 1) == "{"){
      j = findat(s, "}", i + 2)
      if(j > 0 && j < rb_eol(s, i)) return j - i + 1 }
    j = i + 2; d = 0
    while(d < 4 && substr(s, j, 1) ~ /[0-9a-fA-F]/){ j++; d++ }
    if(d == 4) return 6 }
  if(ch == "\\"){ RBESC = "bs"; return 2 }
  if(ch == SQ){ RBESC = "quote"; return 2 }
  return 2 }

# rb_interp(): the interpolation at i, as its spans, and the position after it.
# What it holds is read as code, which is why this calls back into rb_scan().
function rb_interp(s, i, n,   j, depth, ch){
  if(substr(s, i + 1, 1) == "{"){
    depth = 1; j = i + 2
    while(j <= n && depth > 0){
      ch = substr(s, j, 1)
      if(ch == "{") depth++
      else if(ch == "}") depth--
      if(depth == 0) break
      j++ }
    rb_put("Special", "interp", "#{")
    rb_scan(s, i + 2, j)
    if(j <= n){ rb_put("Special", "interp", "}"); return j + 1 }
    return j }
  # #@ivar and #$global, where only the hash is the delimiter
  j = i + 1
  if(substr(s, j, 1) == "@"){ j++; if(substr(s, j, 1) == "@") j++ }
  else if(substr(s, j, 1) == "$") j++
  else return 0
  if(!rb_kwchar(substr(s, j, 1))) return 0
  while(rb_kwchar(substr(s, j, 1))) j++
  rb_put("Special", "interp", "#")
  rb_put("Identifier", "var", substr(s, i + 1, j - i - 1))
  return j }

# rb_string(): a string, a symbol or a word list from i to its closing mark, as
# its spans, and the position after it. The marks at either end are a colour of
# their own, what lies between them the colour of the string.
function rb_string(s, i, n, open, shut, interp, escapes, delim, body, mark,   j, ch, t, depth){
  if(mark == "") mark = "Special"
  rb_put(mark, delim, substr(s, i, length(open)))
  j = i + length(open)
  depth = 0
  while(j <= n){
    ch = substr(s, j, 1)
    if(ch == "\\" && (escapes || index("\\" shut open, substr(s, j + 1, 1)) > 0)){
      t = rb_escape(s, j)
      if(!escapes && substr(s, j + 1, 1) != "\\" && substr(s, j + 1, 1) != shut &&
         substr(s, j + 1, 1) != open){ rb_put("Constant", body, substr(s, j, t)) }
      else rb_put("Special", RBESC, substr(s, j, t))
      j += t; continue }
    if(interp && ch == "#" && (t = rb_interp(s, j, n)) > 0){ j = t; continue }
    if(ch == "\n"){ rb_shut(); rbout = rbout "\n"; j++; continue }
    if(open != shut && ch == open){ depth++; rb_put("Constant", body, ch); j++; continue }
    if(ch == shut){
      if(depth > 0){ depth--; rb_put("Constant", body, ch); j++; continue }
      rb_put(mark, delim, ch); return j + 1 }
    rb_put("Constant", body, ch); j++ }
  return j }

# rb_regexp(): the regular expression at i, as its spans, and the position after
# it. What that file marks inside one - a quantifier, an anchor, a class, an
# escape - is a colour of its own, and each of those is an item of its own.
function rb_regexp(s, i, n, open, shut,   j, k, ch, t, inclass){
  rb_put("Special", "redelim", substr(s, i, length(open)))
  j = i + length(open)
  while(j <= n){
    ch = substr(s, j, 1)
    if(ch == "\\"){
      t = substr(s, j + 1, 1)
      if(t == "" ){ j++; continue }
      if(index("].*?+^$|\\/(){}[", t) > 0){ rb_put("Special", "reesc", substr(s, j, 2)); j += 2; continue }
      if(index("DdHhRSsWw", t) > 0){ rb_put("Special", "reclass", substr(s, j, 2)); j += 2; continue }
      if(index("ABbGZz", t) > 0){ rb_put("Special", "reanchor", substr(s, j, 2)); j += 2; continue }
      if(t == "X"){ rb_put("Special", "redot", substr(s, j, 2)); j += 2; continue }
      t = rb_escape(s, j)
      rb_put("Special", RBESC, substr(s, j, t)); j += t; continue }
    if(ch == shut){
      k = j + 1
      while(substr(s, k, 1) ~ /[iomxneus]/) k++
      rb_put("Special", "redelim", substr(s, j, k - j))
      return k }
    if(ch == "#" && (t = rb_interp(s, j, n)) > 0){ j = t; continue }
    if(ch == "\n"){ rb_shut(); rbout = rbout "\n"; j++; continue }
    if(inclass == 0 && (ch == "*" || ch == "?" || ch == "+")){
      t = j + 1
      if(substr(s, t, 1) ~ /[?+]/) t++
      rb_put("Special", "requant", substr(s, j, t - j)); j = t; continue }
    if(inclass == 0 && (ch == "^" || ch == "$")){ rb_put("Special", "reanchor", ch); j++; continue }
    if(inclass == 0 && ch == "."){ rb_put("Special", "redot", ch); j++; continue }
    if(inclass == 0 && ch == "|"){ rb_put("Special", "respecial", ch); j++; continue }
    if(ch == "["){
      t = (substr(s, j + 1, 1) == "^") ? 2 : 1
      rb_put("Special", "reclass", substr(s, j, t)); j += t; inclass++; continue }
    if(ch == "]" && inclass > 0){ rb_put("Special", "reclass", ch); j++; inclass--; continue }
    if(ch == "&" && substr(s, j + 1, 1) == "&"){
      rb_put("Special", "reand", "&&"); j += 2; continue }
    if(inclass > 0){ rb_put("Constant", "restr", ch); j++; continue }
    if(ch == "]"){ rb_put("Special", "reclass", ch); j++; continue }
    if(ch == "("){
      t = rb_regroup(s, j)
      rb_put("Special", "reparen", substr(s, j, t - j)); j = t; continue }
    if(ch == ")"){ rb_put("Special", "reparen", ch); j++; continue }
    if(ch == "{" && (t = rb_requant(s, j)) > 0){
      rb_put("Special", "requant", substr(s, j, t - j)); j = t; continue }
    rb_put("Constant", "restr", ch); j++ }
  return j }

# rb_regroup(): the end of the mark that opens a group at j, which is a ( on its
# own or one with the ?: ?= ?! ?<name> or ?imx- that names the kind of group.
function rb_regroup(s, j,   k){
  k = j + 1
  if(substr(s, k, 1) != "?") return k
  k++
  if(substr(s, k, 1) == ":" || substr(s, k, 1) == "=" || substr(s, k, 1) == "!" ||
     substr(s, k, 1) == ">") return k + 1
  if(substr(s, k, 1) == "<"){
    if(substr(s, k + 1, 1) == "=" || substr(s, k + 1, 1) == "!") return k + 2
    k++
    while(substr(s, k, 1) ~ /[0-9A-Za-z_]/) k++
    if(substr(s, k, 1) == ">") return k + 1
    return j + 1 }
  while(substr(s, k, 1) ~ /[imx]/) k++
  if(substr(s, k, 1) == "-"){ k++; while(substr(s, k, 1) ~ /[imx]/) k++ }
  if(substr(s, k, 1) == ":") k++
  if(k > j + 2) return k
  return j + 1 }

# rb_requant(): the end of the {2,3} that counts repeats at j, or 0.
function rb_requant(s, j,   k){
  k = j + 1
  while(substr(s, k, 1) ~ /[0-9]/) k++
  if(k == j + 1) return 0
  if(substr(s, k, 1) == ","){ k++; while(substr(s, k, 1) ~ /[0-9]/) k++ }
  if(substr(s, k, 1) != "}") return 0
  k++
  if(substr(s, k, 1) == "?") k++
  return k }

# rb_number(): the end of the number at i, or 0 when there is none there.
function rb_number(s, i, n,   j, k){
  j = i
  if(substr(s, j, 1) == "0" && substr(s, j + 1, 1) ~ /[xX]/){
    j = rb_digits(s, j + 2, "[0-9a-fA-F]")
    if(j == i + 2) return 0 }
  else if(substr(s, j, 1) == "0" && substr(s, j + 1, 1) ~ /[bB]/){
    j = rb_digits(s, j + 2, "[01]")
    if(j == i + 2) return 0 }
  else if(substr(s, j, 1) == "0" && substr(s, j + 1, 1) ~ /[oO]/){
    j = rb_digits(s, j + 2, "[0-7]")
    if(j == i + 2) return 0 }
  else if(substr(s, j, 1) == "0" && substr(s, j + 1, 1) ~ /[dD]/){
    j = rb_digits(s, j + 2, "[0-9]")
    if(j == i + 2) return 0 }
  else if(substr(s, j, 1) == "0" && substr(s, j + 1, 1) ~ /[0-7]/){
    j = rb_digits(s, j + 1, "[0-7]") }
  else if(substr(s, j, 1) ~ /[0-9]/){
    j = rb_digits(s, j, "[0-9]")
    if(substr(s, j, 1) == "." && substr(s, j + 1, 1) ~ /[0-9]/) j = rb_digits(s, j + 1, "[0-9]")
    k = rb_exp(s, j)
    if(k > j) j = k }
  else return 0
  if(substr(s, j, 1) == "r") j++
  if(substr(s, j, 1) == "i") j++
  if(rb_kwchar(substr(s, j, 1))) return 0
  return j }

# rb_minus(): whether the minus at i belongs to the number after it, which that
# file decides by what comes before it: not a word, and not a bracket or a quote
# with a space after it.
function rb_minus(s, i,   ch, back){
  ch = (i > 1 ? substr(s, i - 1, 1) : "")
  if(rb_kwchar(ch)) return 0
  if(ch == " " || ch == "\t"){
    back = rb_back(s, i)
    if(index("]})\"" SQ, back) > 0) return 0 }
  return 1 }

function rb_digits(s, j, kind,   k){
  k = j
  while(substr(s, k, 1) ~ kind ||
        (substr(s, k, 1) == "_" && substr(s, k - 1, 1) ~ kind && substr(s, k + 1, 1) ~ kind)) k++
  return k }

function rb_exp(s, j,   k){
  if(substr(s, j, 1) !~ /[eE]/) return j
  k = j + 1
  if(substr(s, k, 1) ~ /[-+]/) k++
  if(substr(s, k, 1) !~ /[0-9]/) return j
  return rb_digits(s, k, "[0-9]") }

# rb_heredoc(): the body of every heredoc opened on the line that ends at i, put
# out after the line end, and the position after the last of them.
function rb_heredoc(s, i, n,   k, id, e, line, stop, squiggly){
  for(k = 1; k <= rbheren; k++){
    id = rbhereid[k]; squiggly = rbheresq[k]
    stop = 0
    while(i <= n && !stop){
      e = rb_eol(s, i)
      line = substr(s, i, e - i)
      if(line == id || (squiggly && line ~ "^[ \t]*" id "$")){
        if(squiggly && line != id){
          rb_put("Constant", "hbody", substr(line, 1, index(line, substr(id, 1, 1)) - 1)) }
        rb_put("Special", "hdelim", id)
        i = e; stop = 1 }
      else {
        rb_heretext(s, i, e, rbhereint[k])
        i = e }
      if(i <= n){ rb_shut(); rbout = rbout "\n"; i++ } }
  }
  rbheren = 0
  return i }

# rb_heretext(): one line of a heredoc body, with its escapes and what it
# interpolates.
function rb_heretext(s, from, to, interp,   j, ch, t){
  j = from
  while(j < to){
    ch = substr(s, j, 1)
    if(interp && ch == "\\"){ t = rb_escape(s, j); rb_put("Special", RBESC, substr(s, j, t)); j += t; continue }
    if(interp && ch == "#" && (t = rb_interp(s, j, to - 1)) > 0){ j = t; continue }
    rb_put("Constant", "hbody", ch); j++ } }

# rb_heremark(): the end of the heredoc mark at i, or 0 when the << there is a
# shift and not a heredoc. What it opens is remembered until the line ends.
# RBHERESKIP comes back with the length of the << and the dash or the squiggle
# after it, which take no colour.
function rb_heremark(s, i, n,   j, q, id, prev, sq){
  prev = (i > 1 ? substr(s, i - 1, 1) : "")
  if(rb_kwchar(prev) || index("]})\"`" SQ, prev) > 0) return 0
  j = i + 2
  sq = 0
  if(substr(s, j, 1) == "-" || substr(s, j, 1) == "~"){ sq = 1; j++ }
  RBHERESKIP = j - i
  q = substr(s, j, 1)
  if(q == "\"" || q == SQ || q == "`"){
    id = ""
    j++
    while(j <= n && substr(s, j, 1) != q && substr(s, j, 1) != "\n"){ id = id substr(s, j, 1); j++ }
    if(substr(s, j, 1) != q || id == "") return 0
    j++
    rb_here(id, q != SQ, sq)
    return j }
  if(substr(s, j, 1) !~ /[A-Za-z_]/) return 0
  id = ""
  while(rb_kwchar(substr(s, j, 1))){ id = id substr(s, j, 1); j++ }
  rb_here(id, 1, sq)
  return j }

# rb_here(): remember a heredoc until the line it is written on ends.
function rb_here(id, interp, squiggly){
  rbheren++
  rbhereid[rbheren] = id
  rbhereint[rbheren] = interp
  rbheresq[rbheren] = squiggly }

# rb_percent(): the generalized literal at i, if there is one. RBPCT comes back
# with the position after it. %w and %i hold words and take no interpolation,
# %q holds a string that takes none either, and %r holds a regular expression.
function rb_percent(s, i, n,   kind, open, shut, j){
  kind = substr(s, i + 1, 1)
  j = i + 2
  if(kind ~ /[qQwWiIrs]/) open = substr(s, i + 2, 1)
  else { open = kind; kind = "Q"; j = i + 1 }
  if(open == "" || open ~ /[[:alnum:][:space:]]/) return 0
  if(!rb_value(s, i) && kind == "Q") return 0
  shut = open
  if(open == "(") shut = ")"
  else if(open == "[") shut = "]"
  else if(open == "{") shut = "}"
  else if(open == "<") shut = ">"
  if(kind == "r"){
    RBPCT = rb_regexp(s, i, n, substr(s, i, j - i + 1), shut)
    return 1 }
  RBPCT = rb_string(s, i, n, substr(s, i, j - i + 1), shut,
                    (kind == "Q" || kind == "W" || kind == "I"),
                    (kind == "Q" || kind == "W" || kind == "I"),
                    (kind == "s" || kind == "i" || kind == "I") ? "sym" : "delim",
                    (kind == "s" || kind == "i" || kind == "I") ? "sym" : "str",
                    (kind == "s" || kind == "i" || kind == "I") ? "Constant" : "Special")
  return 1 }

# rb_char(): the end of the character written as ?x at i, or 0.
function rb_char(s, i, n,   j, ch){
  ch = substr(s, i + 1, 1)
  if(ch == "" || ch ~ /[[:space:]]/) return 0
  if(ch == "\\"){
    j = i + 1
    return j + rb_escape(s, j) - 1 + 1 }
  if(rb_kwchar(substr(s, i + 2, 1))) return 0
  return i + 2 }

# rb_quotedsym(): the end of the "name": that is a symbol written in quotes with
# the colon after it, or 0. The colon is not part of it.
function rb_quotedsym(s, i, n,   q, j){
  q = substr(s, i, 1)
  j = i + 1
  while(j <= n && substr(s, j, 1) != q && substr(s, j, 1) != "\n"){
    if(substr(s, j, 1) == "\\") j++
    j++ }
  if(substr(s, j, 1) != q) return 0
  if(substr(s, j + 1, 1) != ":" || substr(s, j + 2, 1) == ":") return 0
  return j + 1 }

# rb_symbol(): the symbol at i, put out as its spans, and the position after it,
# or 0 when the colon there opens none. The mark and the name are one span, the
# way the blocks in the tree carry them.
function rb_symbol(s, i, n,   j, ch, q){
  ch = substr(s, i + 1, 1)
  if(ch == "\"" || ch == SQ){
    q = ch
    j = i + 2
    while(j <= n && substr(s, j, 1) != q && substr(s, j, 1) != "\n"){
      if(substr(s, j, 1) == "\\") j++
      j++ }
    if(substr(s, j, 1) != q) return 0
    rb_put("Constant", "sym", substr(s, i, j - i + 1))
    return j + 1 }
  if(ch ~ /[A-Za-z_]/){
    j = i + 1
    while(rb_kwchar(substr(s, j, 1))) j++
    if(substr(s, j, 1) ~ /[?!=]/ && substr(s, j + 1, 1) != "=") j++
    rb_put("Constant", "sym", substr(s, i, j - i))
    return j }
  if(ch == "@" || ch == "$"){
    j = i + 1
    if(ch == "@" && substr(s, j + 1, 1) == "@") j++
    j++
    if(!rb_kwchar(substr(s, j, 1))) return 0
    while(rb_kwchar(substr(s, j, 1))) j++
    rb_put("Constant", "sym", substr(s, i, j - i))
    return j }
  # an operator written as a symbol
  for(j = 3; j >= 1; j--){
    if(substr(s, i + 1, j) in RBOPSYM){
      rb_put("Constant", "sym", substr(s, i, j + 1))
      return i + j + 1 } }
  return 0 }

# rb_scan(): one range of a block, as the spans that colour it. Called again by
# rb_interp() for what an interpolation holds.
function rb_scan(s, from, to,   i, n, ch, prev, j, k, w, t, kind, dot){
  i = from; n = to - 1
  while(i <= n){
    ch = substr(s, i, 1)
    if(ch != " " && ch != "\t" && ch != "\n"){
      RBDOTBEFORE = RBDOT; RBDOT = 0 }

    if(ch == "\n"){
      rb_shut(); rbout = rbout "\n"; i++
      if(rbheren > 0) i = rb_heredoc(s, i, n)
      continue }

    if(ch == "#"){
      j = rb_eol(s, i)
      if(j > to) j = to
      # the line a file opens with, when it names the program that runs it
      if(i == 1 && substr(s, 2, 1) == "!"){
        rb_put("PreProc", "sharpbang", substr(s, i, j - i)); i = j; continue }
      rb_ctext("line", substr(s, i, j - i)); i = j; continue }

    if(ch == "=" && rb_bol(s, i) && substr(s, i, 6) == "=begin"){
      j = findat(s, "\n=end", i)
      j = (j == 0) ? n + 1 : rb_eol(s, j + 1)
      rb_ctext("doc", substr(s, i, j - i)); i = j; continue }

    if(ch == "_" && rb_bol(s, i) && substr(s, i, 7) == "__END__" &&
       (substr(s, i + 7, 1) == "\n" || i + 7 > n)){
      rb_put("Special", "data", "__END__")
      rb_lines("Comment", "data", substr(s, i + 7, n - i - 6)); i = n + 1; continue }

    if((ch == "\"" || ch == SQ) && (t = rb_quotedsym(s, i, n)) > 0){
      rb_put("Constant", "sym", substr(s, i, t - i)); i = t; continue }
    if(ch == "\""){ i = rb_string(s, i, n, "\"", "\"", 1, 1, "delim", "str"); continue }
    if(ch == SQ){ i = rb_string(s, i, n, SQ, SQ, 0, 0, "delim", "str"); continue }
    if(ch == "`"){ i = rb_string(s, i, n, "`", "`", 1, 1, "delim", "str"); continue }

    # a heredoc: the mark is a colour of its own and the body waits for the end
    # of the line
    if(ch == "<" && substr(s, i + 1, 1) == "<" && (t = rb_heremark(s, i, n)) > 0){
      rb_put("", "", substr(s, i, RBHERESKIP))
      rb_put("Special", "hdelim", substr(s, i + RBHERESKIP, t - i - RBHERESKIP))
      i = t; continue }

    if(ch == "%" && rb_percent(s, i, n) > 0){ i = RBPCT; continue }

    if(ch == "/" && rb_value(s, i)){ i = rb_regexp(s, i, n, "/", "/"); continue }

    if(ch == "?" && !rb_kwchar(prev = (i > 1 ? substr(s, i - 1, 1) : "")) &&
       index("]})\"/" SQ, prev) == 0 && (t = rb_char(s, i, n)) > 0){
      rb_put("Constant", "char", substr(s, i, t - i)); i = t; continue }

    prev = (i > 1 ? substr(s, i - 1, 1) : "")
    if(ch == ":" && substr(s, i + 1, 1) != ":" && index("]})\":" SQ, prev) == 0 &&
       (t = rb_symbol(s, i, n)) > 0){ i = t; continue }

    if(ch == "@"){
      j = i + 1
      if(substr(s, j, 1) == "@") j++
      if(rb_kwchar(substr(s, j, 1))){
        while(rb_kwchar(substr(s, j, 1))) j++
        rb_put("Identifier", "var", substr(s, i, j - i)); i = j; continue } }

    # a global, which that file knows by a name, by one of the marks ruby keeps
    # for itself, or by a number
    if(ch == "$"){
      j = i + 1
      if(rb_kwchar(substr(s, j, 1))){
        while(rb_kwchar(substr(s, j, 1))) j++
        rb_put("Identifier", "var", substr(s, i, j - i)); i = j; continue }
      if(index(RBGLOBALCH, substr(s, j, 1)) > 0 && substr(s, j, 1) != ""){
        rb_put("Identifier", "var", substr(s, i, 2)); i = j + 1; continue }
      if(substr(s, j, 1) == "-" && substr(s, j + 1, 1) != ""){
        rb_put("Identifier", "var", substr(s, i, 3)); i = j + 2; continue } }

    prev = (i > 1 ? substr(s, i - 1, 1) : "")
    if(ch == "-" && substr(s, i + 1, 1) ~ /[0-9]/ && rb_minus(s, i) &&
       (t = rb_number(s, i + 1, n)) > 0){
      rb_put("Constant", "num", substr(s, i, t - i)); i = t; continue }
    if(ch ~ /[0-9]/ && !rb_kwchar(prev) && prev != "." && (t = rb_number(s, i, n)) > 0){
      rb_put("Constant", "num", substr(s, i, t - i)); i = t; continue }

    if(RBAFTERDEF && index("+-*/%<>=!~^&|[", ch) > 0){
      for(k = 3; k >= 1; k--){
        if(substr(s, i, k) in RBOPSYM){
          RBAFTERDEF = 0
          rb_put("Identifier", "method", substr(s, i, k)); i += k; break } }
      if(RBAFTERDEF == 0) continue }

    if(ch ~ /[A-Za-z_]/ && !rb_kwchar(prev)){
      j = i
      while(rb_kwchar(substr(s, j, 1))) j++
      if(substr(s, j, 1) ~ /[?!]/ && substr(s, j + 1, 1) != "=") j++
      w = substr(s, i, j - i)
      i = rb_wordout(s, i, j, w, n)
      continue }

    # a dot or a pair of colons is remembered, since the name that follows one
    # is a method call and not a word that file paints
    if(ch == "." && substr(s, i + 1, 1) != "." && substr(s, i - 1, 1) != ".") RBDOT = 1
    if(ch == ":" && substr(s, i + 1, 1) == ":") RBDOT = 1
    if(ch == "&" && substr(s, i + 1, 1) == ".") RBDOT = 1
    # inside a curly block that file reads any name with a colon after it as a
    # hash key, where outside one it wants a space or a comma to follow
    if(ch == "{") RBCURLY++
    else if(ch == "}" && RBCURLY > 0) RBCURLY--
    rb_put("", "", ch); i++ }
  rb_shut() }

# rb_bol(): whether i is the first character of its line.
function rb_bol(s, i){ return i == 1 || substr(s, i - 1, 1) == "\n" }

# rb_wordout(): one word, put out in the colour that file gives it, and the
# position after it - which is past the colon when the word is a hash key.
function rb_wordout(s, i, j, w, n,   kind, nxt, back){
  nxt = substr(s, j, 1)
  if(RBAFTERDEF && nxt != "."){
    RBAFTERDEF--
    rb_put("Identifier", "method", w); return j }
  # a name after a dot or a pair of colons is a method call and no keyword of
  # that file, which nobbles them there on purpose
  if(RBDOTBEFORE && w ~ /^[_a-z]/){ rb_put("", "", w); return j }
  if(!RBAFTERDEF) RBAFTERCLASS = 0
  # a 1.9 hash key: the name is the symbol and the colon after it is not
  if(nxt == ":" && substr(s, j + 1, 1) != ":" &&
     (RBCURLY > 0 || substr(s, j + 1, 1) ~ /[ \t,;]/ ||
      substr(s, j + 1, 1) == "" || substr(s, j + 1, 1) == "\n") &&
     !(w in RBKEY) && rb_back(s, i) != "?"){
    rb_put("Constant", "sym", w)
    rb_put("", "", ":")
    return j + 1 }
  if(w in RBDEFINE){
    rb_put("PreProc", "define", w)
    if(w == "def" || w == "class" || w == "module") rb_open("def", w, i)
    RBAFTERDEF = (w == "def" || w == "undef") ? 1 : (w == "alias" ? 2 : 0)
    RBAFTERCLASS = (w == "class" || w == "module")
    return j }
  if(w == "end"){
    kind = rb_close()
    rb_put(kind == "def" ? "PreProc" : "Statement", kind == "def" ? "define" : "control", w)
    return j }
  if(w in RBBLOCK){
    # the do that closes a for, a while or an until written on the same line is
    # the one that file lets those take, and it opens nothing of its own
    if(w == "do"){
      if(!(rbdepth > 0 && rbstackword[rbdepth] ~ /^(for|while|until)$/ &&
           index(substr(s, rbstackat[rbdepth], i - rbstackat[rbdepth]), "\n") == 0))
        rb_open("stmt", w, i) }
    else if(w == "begin" || w == "case" || w == "for") rb_open("stmt", w, i)
    else if(rb_value(s, i)) rb_open("stmt", w, i)
    rb_put("Statement", "control", w); return j }
  if(w in RBHANDLER){
    if(rbdepth == 0){ rb_put("", "", w); return j }
    kind = rbstack[rbdepth]
    rb_put(kind == "def" ? "PreProc" : "Statement", kind == "def" ? "define" : "control", w)
    return j }
  if(w in RBINCLUDE){ rb_put("PreProc", "include", w); return j }
  if(w in RBMACRO){ rb_put("PreProc", "macro", w); return j }
  if(w in RBSTMT){ rb_put("Statement", "control", w); return j }
  if(w in RBCONST){ rb_put("Constant", "pseudo", w); return j }
  if(w in RBIDENT){ rb_put("Identifier", "predef", w); return j }
  if(w ~ /^[A-Z]/ && rb_back(s, i) != "." && substr(s, j, 1) != "("){
    rb_put("Type", "const", w); return j }
  rb_put("", "", w)
  return j }

# rb(): one ruby block, as the spans that colour it.
function rb(s){
  rbout = ""; rbcls = ""; rbitem = ""; rbdepth = 0; rbheren = 0; RBDOT = 0; RBDOTBEFORE = 0; RBCURLY = 0
  RBAFTERDEF = 0; RBAFTERCLASS = 0
  rb_scan(s, 1, length(s) + 1)
  rb_shut()
  return bs_link(rbout) }

# --- json ---------------------------------------------------------------------
# syntax/json.vim, which paints the marks that hold an object or a list, the
# name of a member, the string or the number that is its value, and the three
# words json has. A name is told from a value by what follows the quote that
# closes it: a colon makes it a name, a comma or a closing mark makes it a
# value, and the quotes themselves take no colour either way. The warnings that
# file keeps are here too, since a block on the site may well be showing what
# went wrong: a word written without quotes, a comment, a semicolon.
function json(s,   n, i, j, ch, t, w){
  jsout = ""; jscls = ""; jsitem = ""
  n = length(s); i = 1
  while(i <= n){
    ch = substr(s, i, 1)
    if(ch == "\n"){ js_shut(); jsout = jsout "\n"; i++; continue }
    if(ch == "{" || ch == "}" || ch == "[" || ch == "]"){
      js_put("Special", "brace", ch); i++; continue }
    if(ch == "\""){ i = js_string(s, i, n); continue }
    if(ch == SQ){
      j = findat(s, SQ, i + 1)
      if(j == 0 || j > js_eol(s, i)) j = js_eol(s, i) - 1
      js_put("Error", "err", substr(s, i, j - i + 1)); i = j + 1; continue }
    if(ch == ";"){ js_put("Error", "err", ch); i++; continue }
    if(ch == "/" && (substr(s, i + 1, 1) == "/" || substr(s, i + 1, 1) == "*")){
      j = (substr(s, i + 1, 1) == "/") ? js_eol(s, i) : i + 2
      js_put("Error", "err", substr(s, i, j - i)); i = j; continue }
    if(ch == "*" && substr(s, i + 1, 1) == "/"){ js_put("Error", "err", "*/"); i += 2; continue }
    if((ch ~ /[0-9]/ || (ch == "-" && substr(s, i + 1, 1) ~ /[0-9]/)) && (t = js_number(s, i, n)) > 0){
      js_put("Constant", "num", substr(s, i, t - i)); i = t; continue }
    if(ch ~ /[A-Za-z_]/){
      j = i
      while(substr(s, j, 1) ~ /[0-9A-Za-z_]/) j++
      w = substr(s, i, j - i)
      if(w == "true" || w == "false") js_put("Constant", "bool", w)
      else if(w == "null") js_put("Identifier", "null", w)
      else js_put("Error", "err", w)
      i = j; continue }
    js_put("", "", ch); i++ }
  js_shut()
  return bs_link(jsout) }

function js_shut(){ if(jscls != ""){ jsout = jsout "</span>"; jscls = "" } jsitem = "" }

function js_put(cls, item, txt){
  if(cls != jscls || item != jsitem){
    js_shut()
    if(cls != "") jsout = jsout "<span class=\"" cls "\">"
    jscls = cls; jsitem = item }
  jsout = jsout codeesc(txt) }

function js_eol(s, i,   p){ p = index(substr(s, i), "\n"); return p == 0 ? length(s) + 1 : i + p - 1 }

# js_string(): the string at i, as its spans, and the position after it. What
# follows the closing quote says whether it was the name of a member or a value,
# and a string that is neither takes no colour at all.
function js_string(s, i, n,   j, k, ch, cls, item, t){
  j = i + 1
  while(j <= n){
    ch = substr(s, j, 1)
    if(ch == "\n") break
    if(ch == "\\"){ j += 2; continue }
    if(ch == "\"") break
    j++ }
  if(substr(s, j, 1) != "\""){ js_put("", "", substr(s, i, j - i)); return j }
  k = j + 1
  while(substr(s, k, 1) ~ /[ \t\r\n]/) k++
  cls = ""; item = ""
  if(substr(s, k, 1) == ":"){ cls = "Statement"; item = "key" }
  else if(index(",}]", substr(s, k, 1)) > 0 && substr(s, k, 1) != ""){ cls = "Constant"; item = "str" }
  js_put("", "", "\"")
  k = i + 1
  while(k < j){
    ch = substr(s, k, 1)
    if(ch == "\\" && cls == "Constant" && (t = js_esclen(s, k)) > 0){
      js_put("Special", "esc", substr(s, k, t)); k += t; continue }
    js_put(cls, item, ch); k++ }
  js_put("", "", "\"")
  return j + 1 }

# js_esclen(): the length of the escape at i, or 0 when json has no such escape.
function js_esclen(s, i,   ch, d){
  ch = substr(s, i + 1, 1)
  if(index("\"\\/bfnrt", ch) > 0 && ch != "") return 2
  if(ch == "u"){
    d = 0
    while(d < 4 && substr(s, i + 2 + d, 1) ~ /[0-9a-fA-F]/) d++
    if(d == 4) return 6 }
  return 0 }

# js_number(): the end of the number at i, or 0. That file colours one only
# where a comma or a closing mark follows it.
function js_number(s, i, n,   j, k){
  j = i
  if(substr(s, j, 1) == "-") j++
  if(substr(s, j, 1) == "0") j++
  else { if(substr(s, j, 1) !~ /[1-9]/) return 0
         while(substr(s, j, 1) ~ /[0-9]/) j++ }
  if(substr(s, j, 1) == "." && substr(s, j + 1, 1) ~ /[0-9]/){
    j++
    while(substr(s, j, 1) ~ /[0-9]/) j++ }
  if(substr(s, j, 1) ~ /[eE]/){
    k = j + 1
    if(substr(s, k, 1) ~ /[-+]/) k++
    if(substr(s, k, 1) ~ /[0-9]/){
      while(substr(s, k, 1) ~ /[0-9]/) k++
      j = k } }
  k = j
  while(substr(s, k, 1) ~ /[ \t\r\n]/) k++
  if(index(",}]", substr(s, k, 1)) == 0 || substr(s, k, 1) == "") return 0
  return j }

# --- the line kinds -----------------------------------------------------------
# What follows are the formats vim reads a line at a time and nothing more: a
# crontab, a unit file, the two files a debian package is described by, and a
# diff. Each is small, so they share the one writer rather than carrying five
# copies of cl_put() between them.
function cfg_shut(){ if(cfgcls != ""){ cfgout = cfgout "</span>"; cfgcls = "" } cfgitem = "" }

function cfg_put(cls, item, txt){
  if(cls != cfgcls || item != cfgitem){
    cfg_shut()
    if(cls != "") cfgout = cfgout "<span class=\"" cls "\">"
    cfgcls = cls; cfgitem = item }
  cfgout = cfgout codeesc(txt) }

# cfg_lines(): the block split into lines, and the number of them. Every format
# below walks that array and writes one line at a time.
function cfg_lines(s, out,   n){
  n = split(s, out, "\n")
  cfgout = ""; cfgcls = ""; cfgitem = ""
  return n }

# cfg_end(): the newline between two lines, which no span carries over.
function cfg_end(i, n){ if(i < n){ cfg_shut(); cfgout = cfgout "\n" } }

# --- crontab ------------------------------------------------------------------
# syntax/crontab.vim: the five fields of a line each have a colour of their own,
# the command after them is a statement, a line that sets a variable is an
# identifier up to the equals sign, and a nickname like @reboot stands in for the
# fields. Left out is the second-level colouring that file gives the names of
# months and days, which it only reaches through the fields it has already
# painted, so the colour on screen is the same.
function crontab(s,   n, i, k, line, lines, j, rest, cls, ch){
  n = cfg_lines(s, lines)
  for(i = 1; i <= n; i++){
    line = lines[i]
    if(line ~ /^[ \t]*#/){ cfg_put("Comment", "cmnt", line); cfg_end(i, n); continue }
    if(line ~ /^[ \t]*@[a-z_]+/){
      j = match(line, /@[a-z_]+/) + RLENGTH
      cfg_put("Special", "nick", substr(line, 1, j - 1))
      rest = substr(line, j)
      k = match(rest, /[^ \t]/)
      if(k > 0){ cfg_put("", "", substr(rest, 1, k - 1)); cfg_put("Statement", "cmd", substr(rest, k)) }
      else cfg_put("", "", rest)
      cfg_end(i, n); continue }
    if(line ~ /^[ \t]*[A-Za-z_][A-Za-z0-9_]*[ \t]*=/){
      j = index(line, "=")
      cfg_put("Identifier", "var", substr(line, 1, j - 1))
      cfg_put("", "", substr(line, j))
      cfg_end(i, n); continue }
    if(line !~ /^[ \t]*[-~0-9\/,.*]/){ cfg_put("", "", line); cfg_end(i, n); continue }
    j = 1
    for(k = 1; k <= 5; k++){
      cls = (k == 1 || k == 4) ? "Constant" : ((k == 3) ? "Type" : "PreProc")
      rest = substr(line, j)
      if(k == 1) match(rest, /^[ \t]*[-~0-9\/,.*]+/)
      else match(rest, /^[ \t]+[-~a-zA-Z0-9\/,.*]+/)
      if(RSTART != 1) break
      cfg_put(cls, "f" k, substr(rest, 1, RLENGTH))
      j += RLENGTH }
    rest = substr(line, j)
    k = match(rest, /[^ \t]/)
    if(k > 0){ cfg_put("", "", substr(rest, 1, k - 1)); cfg_put("Statement", "cmd", substr(rest, k)) }
    else cfg_put("", "", rest)
    cfg_end(i, n) }
  cfg_shut()
  return bs_link(cfgout) }

# --- dosini -------------------------------------------------------------------
# syntax/dosini.vim, which is what vim reads a systemd unit with: the name of a
# section is a special, the name of a setting a type, and what it is set to a
# string - or a number, which is the same colour under another name.
function dosini(s,   n, i, line, lines, j){
  n = cfg_lines(s, lines)
  for(i = 1; i <= n; i++){
    line = lines[i]
    if(line ~ /^[#;]/){ cfg_put("Comment", "cmnt", line); cfg_end(i, n); continue }
    if(line ~ /^[ \t]*\[/){
      j = index(line, "]")
      if(j > 0){
        cfg_put("Special", "header", substr(line, 1, j))
        cfg_put("", "", substr(line, j + 1)) }
      else cfg_put("Special", "header", line)
      cfg_end(i, n); continue }
    j = index(line, "=")
    if(j > 0){
      cfg_put("Type", "label", substr(line, 1, j - 1))
      cfg_put("", "", "=")
      if(substr(line, j + 1) != "")
        cfg_put("Constant", substr(line, j + 1) ~ /^[ \t]*[0-9.e+-]+[ \t]*$/ ? "num" : "value",
                substr(line, j + 1)) }
    else cfg_put("", "", line)
    cfg_end(i, n) }
  cfg_shut()
  return bs_link(cfgout) }

# --- debcontrol ---------------------------------------------------------------
# syntax/debcontrol.vim: the name of a field it knows is a keyword and what
# follows takes no colour, a line it does not know at all is the special it
# paints one,
# and a variable or an address inside a field is an identifier. The field names
# are that file, less the ones it spells with a pattern for the x- prefixes
# nobody writes in an article.
function debcontrol(s,   n, i, line, lines, j, key, val){
  n = cfg_lines(s, lines)
  for(i = 1; i <= n; i++){
    line = lines[i]
    if(line ~ /^#/){ cfg_put("Comment", "cmnt", line); cfg_end(i, n); continue }
    if(line ~ /^[ \t]/ || line == ""){ deb_value("", line); cfg_end(i, n); continue }
    j = index(line, ":")
    key = (j > 0) ? substr(line, 1, j - 1) : ""
    if(j > 0 && tolower(key) in DEBFIELD){
      val = substr(line, j + 1)
      match(val, /^[ \t]*/)
      cfg_put("Statement", "key", substr(line, 1, j) substr(val, 1, RLENGTH))
      deb_value("val", substr(val, RLENGTH + 1)) }
    else cfg_put("Special", "else", line)
    cfg_end(i, n) }
  cfg_shut()
  return bs_link(cfgout) }

# deb_value(): what a field is set to, with the variables and the addresses in it
# picked out the way that file picks them out.
function deb_value(item, v,   i, n, ch, run, j){
  n = length(v); i = 1; run = ""
  while(i <= n){
    ch = substr(v, i, 1)
    if(ch == "$" && substr(v, i + 1, 1) == "{"){
      j = findat(v, "}", i + 2)
      if(j > 0){
        cfg_put("", item, run); run = ""
        cfg_put("Identifier", "var", substr(v, i, j - i + 1)); i = j + 1; continue } }
    if(ch == "<"){
      j = findat(v, ">", i + 1)
      if(j > 0){
        cfg_put("", item, run); run = ""
        cfg_put("Identifier", "email", substr(v, i, j - i + 1)); i = j + 1; continue } }
    run = run ch; i++ }
  if(run != "") cfg_put("", item, run) }

# --- debchangelog -------------------------------------------------------------
# syntax/debchangelog.vim: the line a version opens with is an error until the
# pieces of it are picked out - the name of the package, the version in
# brackets, the release it goes to, and the urgency after the semicolon - the
# line that signs it off is an identifier, and what is written between them
# takes no colour at all.
function debchangelog(s,   n, i, line, lines, j, k){
  n = cfg_lines(s, lines)
  for(i = 1; i <= n; i++){
    line = lines[i]
    if(line ~ /^[ ]/){
      if(line ~ /^ [^ ]/) cfg_put("Identifier", "footer", line)
      else cfg_put("", "", line)
      cfg_end(i, n); continue }
    if(line == ""){ cfg_end(i, n); continue }
    j = match(line, /^[[:alnum:]][[:alnum:].+-]* /)
    if(j != 1){ cfg_put("Error", "header", line); cfg_end(i, n); continue }
    cfg_put("Comment", "name", substr(line, 1, RLENGTH))
    k = RLENGTH + 1
    if(match(substr(line, k), /^\([^)]*\)/) == 1){
      cfg_put("Identifier", "version", substr(line, k, RLENGTH)); k += RLENGTH }
    if(match(substr(line, k), /^ UNRELEASED/) == 1){
      cfg_put("WarningMsg", "unreleased", substr(line, k, RLENGTH)); k += RLENGTH }
    else if(match(substr(line, k), /^ [A-Za-z][-[:alnum:]]*/) == 1){
      cfg_put("Identifier", "target", substr(line, k, RLENGTH)); k += RLENGTH }
    if(match(substr(line, k), /^; *urgency=[a-z]+/) == 1){
      cfg_put("Identifier", "kv", substr(line, k, RLENGTH)); k += RLENGTH }
    if(substr(line, k) != "") cfg_put("Error", "header", substr(line, k))
    cfg_end(i, n) }
  cfg_shut()
  return bs_link(cfgout) }

# --- diff ---------------------------------------------------------------------
# syntax/diff.vim, which reads a line by the character it opens with: a line
# added, a line taken away, a line changed, and the lines that say where in the
# file the change is. The order the tests are in is the order that file defines
# them in, since the last one it defines is the one it uses.
function diff(s,   n, i, line, lines){
  n = cfg_lines(s, lines)
  for(i = 1; i <= n; i++){
    line = lines[i]
    if(line ~ /^#/) cfg_put("Comment", "cmnt", line)
    else if(line ~ /^index [0-9a-f][0-9a-f][0-9a-f][0-9a-f]/) cfg_put("PreProc", "index", line)
    else if(line ~ /^--- / || line ~ /^\+\+\+ / || line ~ /^\*\*\* /) cfg_put("Type", "file", line)
    else if(line ~ /^diff[ \t]/ || line ~ /^Index: / || line ~ /^==== /) cfg_put("Type", "file", line)
    else if(line ~ /^@/) diff_hunk(line)
    else if(line ~ /^[0-9]/ || line ~ /^\*\*\*\*/ || line == "---") cfg_put("Statement", "line", line)
    else if(line ~ /^! /) cfg_put("Changed", "changed", line)
    else if(line ~ /^\+/ || line ~ /^>/) cfg_put("Added", "added", line)
    else if(line ~ /^-/ || line ~ /^</) cfg_put("Removed", "removed", line)
    else if(line ~ /^Only in / || line ~ /^Common subdirectories: /) cfg_put("Constant", "only", line)
    else if(line ~ /^Files .* (differ|are identical)$/) cfg_put("Constant", "only", line)
    else if(line ~ /^Binary files .* differ$/) cfg_put("Constant", "only", line)
    else if(line ~ /^\\ No newline at end of file/) cfg_put("Constant", "only", line)
    else cfg_put("", "", line)
    cfg_end(i, n) }
  cfg_shut()
  return bs_link(cfgout) }

# diff_hunk(): the @@ line, where the name of what the change is inside is a
# colour of its own.
function diff_hunk(line,   j){
  j = index(substr(line, 4), "@@")
  if(j == 0){ cfg_put("Statement", "line", line); return }
  j += 5
  cfg_put("Statement", "line", substr(line, 1, j - 1))
  cfg_put("PreProc", "subname", substr(line, j)) }

# --- sshconfig ----------------------------------------------------------------
# syntax/sshconfig.vim: the word a line opens with is a keyword, Host and Match
# are a type instead, and what follows is looked at for the values that file
# knows - a number, an address, one of the words an option is set to, the % of a
# token, the * of a pattern - the rest of it taking no colour. Everything after
# a Host or a HostName is an address whatever it looks like, which is that file
# reading it that way.
function sshconfig(s,   n, i, line, lines, j, w, rest){
  n = cfg_lines(s, lines)
  for(i = 1; i <= n; i++){
    line = lines[i]
    if(line ~ /^[ \t]*#/){ cfg_put("Comment", "cmnt", line); cfg_end(i, n); continue }
    if(match(line, /^[ \t]*[A-Za-z]+/) != 1){ cfg_put("", "", line); cfg_end(i, n); continue }
    w = substr(line, 1, RLENGTH)
    rest = substr(line, RLENGTH + 1)
    sub(/^[ \t]+/, "", w)
    j = RLENGTH - length(w)
    if(j > 0) cfg_put("", "", substr(line, 1, j))
    if(tolower(w) == "host" || tolower(w) == "match"){
      cfg_put("Type", "sect", w)
      # after a Host the whole of the rest is the address it names
      if(tolower(w) == "host" && rest ~ /^ ./){
        cfg_put("", "", " ")
        cfg_put("Constant", "host", substr(rest, 2)) }
      else ssh_value(rest) }
    else {
      cfg_put(tolower(w) in SSHKEY ? "Statement" : "", "key", w)
      if(tolower(w) == "hostname" && rest ~ /^ ./){
        cfg_put("", "", " ")
        cfg_put("Constant", "host", substr(rest, 2)) }
      else ssh_value(rest) }
    cfg_end(i, n) }
  cfg_shut()
  return bs_link(cfgout) }

# ssh_value(): what an option is set to, with the pieces that file has a colour
# for picked out of it.
function ssh_value(v,   i, n, ch, w, j, run){
  n = length(v); i = 1; run = ""
  while(i <= n){
    ch = substr(v, i, 1)
    if(ch == "#" && (i == 1 || substr(v, i - 1, 1) ~ /[ \t]/)){
      cfg_put("", "val", run); run = ""
      cfg_put("Comment", "cmnt", substr(v, i)); return }
    if(ch == "*" || ch == "?"){
      cfg_put("", "val", run); run = ""
      cfg_put("Special", "glob", ch); i++; continue }
    if(ch == "%" && substr(v, i + 1, 1) ~ /[rhplLdun]/){
      cfg_put("", "val", run); run = ""
      cfg_put("Identifier", "token", substr(v, i, 2)); i += 2; continue }
    if(ch ~ /[0-9]/ && !ssh_word(i > 1 ? substr(v, i - 1, 1) : "")){
      j = i
      while(substr(v, j, 1) ~ /[0-9.:]/) j++
      w = substr(v, i, j - i)
      if(!ssh_word(substr(v, j, 1))){
        cfg_put("", "val", run); run = ""
        cfg_put("Constant", w ~ /^[0-9]+$/ ? "num" : "host", w); i = j; continue } }
    if(ch ~ /[A-Za-z]/ && !ssh_word(i > 1 ? substr(v, i - 1, 1) : "")){
      j = i
      while(ssh_word(substr(v, j, 1))) j++
      w = substr(v, i, j - i)
      # a name written in parts with dots between them is an address to that
      # file, whatever the parts happen to be
      if(w ~ /^[-A-Za-z0-9]+(\.[-A-Za-z0-9]+)*\.[-A-Za-z0-9][-A-Za-z0-9]+(:[0-9]+)?$/){
        cfg_put("", "val", run); run = ""
        cfg_put("Constant", "host", w); i = j; continue }
      if(tolower(w) in SSHENUM || tolower(w) in SSHDEP){
        cfg_put("", "val", run); run = ""
        cfg_put(tolower(w) in SSHDEP ? "Error" : "Identifier", "enum", w); i = j; continue }
      run = run w; i = j; continue }
    run = run ch; i++ }
  if(run != "") cfg_put("", "val", run) }

function ssh_word(ch){ return ch != "" && ch ~ /[-0-9A-Za-z_.@]/ }

# --- make ---------------------------------------------------------------------
# syntax/make.vim: a target is a function, the name in front of an equals sign
# and every $(...) an identifier, the words make has of its own a statement or a
# precondition, and the lines under a target - the ones that open with a tab -
# are the commands, which that file gives the colour of a number. Left out of it
# is what no makefile on the site reaches: the define block, the nmake
# directives written with an exclamation mark, and the strings it picks out
# inside a command.
function make(s,   n, i, line, lines, j, k, w){
  n = cfg_lines(s, lines)
  makecont = 0
  for(i = 1; i <= n; i++){
    line = lines[i]
    # a line ended with a backslash carries the one before it on, and the indent
    # it opens with belongs to that backslash
    if(makecont){
      match(line, /^[ \t]*/)
      if(RLENGTH > 0) cfg_put("Special", "next", substr(line, 1, RLENGTH))
      make_body(makecontitem, substr(line, RLENGTH + 1), makecontcls)
      cfg_end(i, n); continue }
    if(line ~ /^\t/){
      j = match(line, /^\t[ \t]*[@+-]+/)
      if(j == 1){ cfg_put("Special", "spec", substr(line, 1, RLENGTH)); k = RLENGTH + 1 }
      else k = 1
      make_body("cmd", substr(line, k), "Constant")
      cfg_end(i, n); continue }
    if(line ~ /^[ \t]*#/){ make_comment(line); cfg_end(i, n); continue }
    if(match(line, /^ *(ifn?(eq|def)|else|endif)([^A-Za-z0-9_]|$)/) == 1){
      cfg_put("PreProc", "cond", substr(line, 1, RLENGTH))
      make_body("", substr(line, RLENGTH + 1), "")
      cfg_end(i, n); continue }
    if(match(line, /^ *[-s]?include[ \t]/) == 1){
      cfg_put("PreProc", "incl", line); cfg_end(i, n); continue }
    if(match(line, /^ *(export|unexport|override|vpath)([^A-Za-z0-9_]|$)/) == 1){
      cfg_put(substr(line, 1, RLENGTH) ~ /vpath/ ? "Statement" : "Identifier", "stmt",
              substr(line, 1, RLENGTH))
      make_body("", substr(line, RLENGTH + 1), "")
      cfg_end(i, n); continue }
    j = match(line, /^ *\.[A-Za-z0-9_.\/\t -]+[ \t]*::?([^=]|$)/)
    if(j == 1 && line ~ /^ *\.(SUFFIXES|PHONY|DEFAULT|PRECIOUS|IGNORE|SILENT|EXPORT_ALL_VARIABLES|KEEP_STATE|LIBPATTERNS|NOTPARALLEL|DELETE_ON_ERROR|INTERMEDIATE|POSIX|SECONDARY|ONESHELL)([^A-Za-z0-9_]|$)/){
      k = index(line, ":")
      if(substr(line, k + 1, 1) == ":") k++
      cfg_put("Statement", "spectarget", substr(line, 1, k))
      make_body("", substr(line, k + 1), "")
      cfg_end(i, n); continue }
    j = match(line, /^ *[^:#= \t][^:#=]*[ \t]*(::?|[:+?!*]?=)/)
    if(j == 1){
      k = match(line, /(::?=|[:+?!*]?=|::?)/)
      w = substr(line, RSTART, RLENGTH)
      if(w ~ /=/){
        cfg_put("Identifier", "var", substr(line, 1, RSTART - 1))
        cfg_put("", "", w)
        make_body("", substr(line, RSTART + RLENGTH), "")
        cfg_end(i, n); continue }
      if(substr(line, RSTART + RLENGTH) !~ /^=/){
        make_target(substr(line, 1, RSTART - 1) w)
        make_body("", substr(line, RSTART + RLENGTH), "")
        cfg_end(i, n); continue } }
    make_body("", line, "")
    cfg_end(i, n) }
  cfg_shut()
  return bs_link(cfgout) }

# make_body(): the rest of a line, and the backslash that carries it on to the
# next one, which that file gives a colour of its own.
function make_body(item, v, cls){
  if(v ~ /\\$/){
    make_text(item, substr(v, 1, length(v) - 1), cls)
    cfg_put("Special", "next", "\\")
    makecont = 1; makecontcls = cls; makecontitem = item
    return }
  make_text(item, v, cls)
  makecont = 0 }

# make_target(): the name of a target and the colon after it, which are the one
# colour, and a % inside it, which that file reads as a name of its own.
function make_target(t,   i, n, ch, run){
  n = length(t); i = 1; run = ""
  while(i <= n){
    ch = substr(t, i, 1)
    if(ch == "%"){
      if(run != ""){ cfg_put("Identifier", "target", run); run = "" }
      cfg_put("Identifier", "ident", ch); i++; continue }
    run = run ch; i++ }
  if(run != "") cfg_put("Identifier", "target", run) }

# make_comment(): a comment, with the words that file picks out of it.
function make_comment(line,   i, n, w, p, run){
  n = length(line); i = 1; run = ""
  while(i <= n){
    if(substr(line, i, 1) ~ /[A-Za-z]/ && !make_word(i > 1 ? substr(line, i - 1, 1) : "")){
      p = i
      while(make_word(substr(line, p, 1))) p++
      w = substr(line, i, p - i)
      if(w == "TODO" || w == "FIXME" || w == "XXX"){
        cfg_put("Comment", "cmnt", run); run = ""
        cfg_put("Todo", "todo", w) }
      else run = run w
      i = p; continue }
    run = run substr(line, i, 1); i++ }
  cfg_put("Comment", "cmnt", run) }

function make_word(ch){ return ch != "" && ch ~ /[0-9A-Za-z_]/ }

# make_text(): a stretch of a line that is not a name or a keyword, with the
# $(...) in it picked out and, inside those, the functions make knows.
function make_text(item, v, cls,   i, n, ch, j, run, depth, w){
  n = length(v); i = 1; run = ""
  while(i <= n){
    ch = substr(v, i, 1)
    if(ch == "#"){
      cfg_put(cls, item, run); run = ""
      make_comment(substr(v, i)); return }
    if(ch == "$"){
      j = i + 1
      if(substr(v, j, 1) == "(" || substr(v, j, 1) == "{"){
        depth = 1; j++
        while(j <= n && depth > 0){
          if(substr(v, j, 1) == "(" || substr(v, j, 1) == "{") depth++
          else if(substr(v, j, 1) == ")" || substr(v, j, 1) == "}") depth--
          if(depth == 0) break
          j++ }
        cfg_put(cls, item, run); run = ""
        w = substr(v, i, j - i + 1)
        make_ident(w)
        i = j + 1; continue }
      cfg_put(cls, item, run); run = ""
      cfg_put("Identifier", "ident", substr(v, i, 2)); i += 2; continue }
    if(ch == "%"){
      cfg_put(cls, item, run); run = ""
      cfg_put("Identifier", "ident", ch); i++; continue }
    run = run ch; i++ }
  if(run != "") cfg_put(cls, item, run) }

# make_ident(): one $(...), where the name of a function make has is a statement
# and the rest of it an identifier.
function make_ident(w,   j, f){
  if(match(substr(w, 3), /^[a-z-]+/) > 0){
    f = substr(w, 3, RLENGTH)
    if(f in MAKEFUNC){
      cfg_put("Identifier", "ident", substr(w, 1, 2))
      cfg_put("Statement", "func", f)
      cfg_put("Identifier", "ident", substr(w, 3 + length(f)))
      return } }
  cfg_put("Identifier", "ident", w) }

# --- cmake --------------------------------------------------------------------
# syntax/cmake.vim: the name of a command is a function, what a ${ } holds is a
# variable inside a value, a string is a string, and the words a command takes
# as arguments have a colour of their own. That file carries a list of every
# such word for every command there is, seventeen hundred variables and a
# thousand arguments; what is here is the commands, which are the shape of a
# cmake file, and the arguments and the variables the blocks on the site use. A
# word it does not know is left plain, which is what a name of your own gets.
function cmake(s,   n, i, ch, j, w, depth){
  cmkout = ""; cmkcls = ""; cmkitem = ""
  n = length(s); i = 1; depth = 0
  while(i <= n){
    ch = substr(s, i, 1)
    if(ch == "\n"){ cmk_shut(); cmkout = cmkout "\n"; i++; continue }
    if(ch == "#"){
      j = cmk_eol(s, i)
      cmk_put("Comment", "cmnt", substr(s, i, j - i)); i = j; continue }
    if(ch == "\""){ i = cmk_string(s, i, n); continue }
    if(ch == "$" && substr(s, i + 1, 4) == "ENV{"){
      j = findat(s, "}", i + 5)
      if(j == 0) j = cmk_eol(s, i) - 1
      cmk_put("Special", "env", substr(s, i, j - i + 1)); i = j + 1; continue }
    if(ch == "$" && substr(s, i + 1, 1) == "{"){ i = cmk_value(s, i, n); continue }
    if(ch == "(" ){ depth++; cmk_put("", "", ch); i++; continue }
    if(ch == ")" ){ if(depth > 0) depth--; cmk_put("", "", ch); i++; continue }
    if(ch ~ /[A-Za-z_]/ && !cmk_word(i > 1 ? substr(s, i - 1, 1) : "")){
      j = i
      while(cmk_word(substr(s, j, 1))) j++
      w = substr(s, i, j - i)
      if(depth == 0){
        if(w in CMAKECMD) cmk_put("Identifier", "cmd", w)
        else if(w in CMAKEDEP) cmk_put("WarningMsg", "dep", w)
        else cmk_put("", "", w) }
      else if(w in CMAKEKW) cmk_put("ModeMsg", "kw", w)
      else if(w in CMAKEVAR) cmk_put("Identifier", "var", w)
      else cmk_put("", "", w)
      i = j; continue }
    cmk_put("", "", ch); i++ }
  cmk_shut()
  return bs_link(cmkout) }

function cmk_shut(){ if(cmkcls != ""){ cmkout = cmkout "</span>"; cmkcls = "" } cmkitem = "" }

function cmk_put(cls, item, txt){
  if(cls != cmkcls || item != cmkitem){
    cmk_shut()
    if(cls != "") cmkout = cmkout "<span class=\"" cls "\">"
    cmkcls = cls; cmkitem = item }
  cmkout = cmkout codeesc(txt) }

function cmk_eol(s, i,   p){ p = index(substr(s, i), "\n"); return p == 0 ? length(s) + 1 : i + p - 1 }

function cmk_word(ch){ return ch != "" && ch ~ /[0-9A-Za-z_]/ }

# cmk_value(): a ${ } and what it holds, which is the colour of a value with the
# names that file knows picked out of it.
function cmk_value(s, i, n,   j, k, w){
  j = findat(s, "}", i + 2)
  if(j == 0 || j > cmk_eol(s, i)){ cmk_put("", "", substr(s, i, 2)); return i + 2 }
  cmk_put("Type", "value", "${")
  k = i + 2
  while(k < j){
    if(substr(s, k, 1) ~ /[A-Za-z_]/ && !cmk_word(k > 1 ? substr(s, k - 1, 1) : "")){
      w = k
      while(cmk_word(substr(s, w, 1))) w++
      cmk_put(substr(s, k, w - k) in CMAKEVAR ? "Identifier" : "Type",
              substr(s, k, w - k) in CMAKEVAR ? "var" : "value", substr(s, k, w - k))
      k = w; continue }
    cmk_put("Type", "value", substr(s, k, 1)); k++ }
  cmk_put("Type", "value", "}")
  return j + 1 }

# cmk_string(): a string, where an escape and a ${ } keep their own colours.
function cmk_string(s, i, n,   j, ch){
  cmk_put("Constant", "str", "\"")
  j = i + 1
  while(j <= n){
    ch = substr(s, j, 1)
    if(ch == "\\" && substr(s, j + 1, 1) ~ /[\\"nt]/){
      cmk_put("Special", "esc", substr(s, j, 2)); j += 2; continue }
    if(ch == "$" && substr(s, j + 1, 1) == "{"){ j = cmk_value(s, j, n); continue }
    if(ch == "\n"){ cmk_shut(); cmkout = cmkout "\n"; j++; continue }
    cmk_put("Constant", "str", ch); j++
    if(ch == "\"") break }
  return j }

# --- html and javascript ------------------------------------------------------
# syntax/html.vim and the syntax/javascript.vim it pulls in for what a <script>
# holds. The marks of a tag are one colour and the name inside them another, an
# attribute that file has a name for is a type and one it does not is the colour
# of the tag, and an entity is a special. Inside a script the plain text of the
# code is a special as well, that file giving the whole region that colour, and
# what javascript knows sits on top of it: the words, the strings, the numbers,
# the comments, and the braces, which it gives the colour of a function. The
# parentheses take no colour at all, which is that file and not an oversight
# here. Left out is what no block on the site reaches: the css a <style> holds,
# the folding, and the regular expression written without a mark in front of it.
function html(s,   n, i, ch, j, k, t){
  htout = ""; htcls = ""; htitem = ""
  n = length(s); i = 1
  while(i <= n){
    ch = substr(s, i, 1)
    if(ch == "\n"){ ht_shut(); htout = htout "\n"; i++; continue }
    if(substr(s, i, 4) == "<!--"){
      j = findat(s, "-->", i + 4)
      j = (j == 0) ? n + 1 : j + 3
      ht_lines("Comment", "cmnt", substr(s, i, j - i)); i = j; continue }
    if(ch == "<" && substr(s, i + 1, 1) ~ /[A-Za-z\/!]/){
      j = ht_tag(s, i, n)
      if(substr(s, i, 8) ~ /^<script[ >]/){
        k = ht_find(s, j, "</script")
        if(k > j) jv_scan(s, j, k, "Special")
        i = (k > j) ? k : j
        continue }
      i = j; continue }
    if(ch == "&" && (j = ht_entity(s, i)) > 0){
      ht_put("Special", "ent", substr(s, i, j - i)); i = j; continue }
    ht_put("", "", ch); i++ }
  ht_shut()
  return bs_link(htout) }

function javascript(s){
  htout = ""; htcls = ""; htitem = ""
  jv_scan(s, 1, length(s) + 1, "")
  ht_shut()
  return bs_link(htout) }

function ht_shut(){ if(htcls != ""){ htout = htout "</span>"; htcls = "" } htitem = "" }

function ht_put(cls, item, txt){
  if(cls != htcls || item != htitem){
    ht_shut()
    if(cls != "") htout = htout "<span class=\"" cls "\">"
    htcls = cls; htitem = item }
  htout = htout codeesc(txt) }

function ht_lines(cls, item, txt,   p){
  while((p = index(txt, "\n")) > 0){
    if(p > 1) ht_put(cls, item, substr(txt, 1, p - 1))
    ht_shut(); htout = htout "\n"
    txt = substr(txt, p + 1) }
  if(txt != "") ht_put(cls, item, txt) }

function ht_eol(s, i,   p){ p = index(substr(s, i), "\n"); return p == 0 ? length(s) + 1 : i + p - 1 }

function ht_word(ch){ return ch != "" && ch ~ /[-0-9A-Za-z_:]/ }

# ht_find(): where the closing tag at or after i begins, or 0.
function ht_find(s, i, what,   j){ j = findat(s, what, i); return j }

# ht_entity(): the end of the &...; at i, or 0.
function ht_entity(s, i,   j){
  j = i + 1
  if(substr(s, j, 1) == "#") j++
  while(substr(s, j, 1) ~ /[0-9A-Za-z]/) j++
  if(substr(s, j, 1) == ";" && j > i + 1) return j + 1
  return 0 }

# ht_tag(): one tag, as its spans, and the position after it. The marks and
# whatever the tag holds that has no name of its own are the one colour, the
# name of the tag another, and an attribute that file knows a third.
function ht_tag(s, i, n,   j, k, w, closing){
  closing = (substr(s, i + 1, 1) == "/")
  j = i + (closing ? 2 : 1)
  ht_put("Identifier", closing ? "endtag" : "tag", substr(s, i, j - i))
  k = j
  while(ht_word(substr(s, k, 1))) k++
  w = substr(s, j, k - j)
  ht_put(tolower(w) in HTMLTAG ? "Statement" : "Identifier",
         tolower(w) in HTMLTAG ? "name" : "tag", w)
  j = k
  while(j <= n){
    ch = substr(s, j, 1)
    if(ch == ">"){ ht_put("Identifier", closing ? "endtag" : "tag", ">"); return j + 1 }
    if(ch == "\n"){ ht_shut(); htout = htout "\n"; j++; continue }
    if(ch == "\"" || ch == SQ){
      k = findat(s, ch, j + 1)
      if(k == 0 || k > ht_eol(s, j)) k = ht_eol(s, j) - 1
      ht_put("Constant", "value", substr(s, j, k - j + 1)); j = k + 1; continue }
    if(ch ~ /[A-Za-z]/ && !ht_word(substr(s, j - 1, 1))){
      k = j
      while(ht_word(substr(s, k, 1))) k++
      w = substr(s, j, k - j)
      ht_put(tolower(w) in HTMLARG ? "Type" : "Identifier",
             tolower(w) in HTMLARG ? "arg" : "tag", w)
      j = k; continue }
    ht_put("Identifier", closing ? "endtag" : "tag", ch); j++ }
  return j }

# jv_scan(): the javascript in the range from..to, where base is the colour the
# text of it takes - a special inside a script, nothing when a block is
# javascript and nothing else.
function jv_scan(s, from, to, base,   i, n, ch, j, k, w, prev){
  i = from; n = to - 1
  while(i <= n){
    ch = substr(s, i, 1)
    if(ch == "\n"){ ht_shut(); htout = htout "\n"; i++; continue }
    if(ch == "/" && substr(s, i + 1, 1) == "/"){
      j = ht_eol(s, i)
      if(j > to) j = to
      jv_comment(substr(s, i, j - i)); i = j; continue }
    if(ch == "/" && substr(s, i + 1, 1) == "*"){
      j = findat(s, "*/", i + 2)
      j = (j == 0 || j > n) ? n + 1 : j + 2
      jv_comment(substr(s, i, j - i)); i = j; continue }
    if(ch == "\"" || ch == SQ){ i = jv_string(s, i, n, ch); continue }
    if(ch == "`"){ i = jv_template(s, i, n); continue }
    if(ch == "/" && jv_regexp(s, i)){ i = jv_slash(s, i, n); continue }
    if(ch ~ /[0-9]/ && !jv_word(i > 1 ? substr(s, i - 1, 1) : "") && (j = jv_number(s, i)) > i){
      ht_put("Constant", "num", substr(s, i, j - i)); i = j; continue }
    if(ch ~ /[A-Za-z_$]/ && !jv_word(i > 1 ? substr(s, i - 1, 1) : "")){
      j = i
      while(jv_word(substr(s, j, 1))) j++
      w = substr(s, i, j - i)
      if(w in JSSTMT)       ht_put("Statement", "kw", w)
      else if(w in JSTYPE)  ht_put("Type", "type", w)
      else if(w in JSCONST) ht_put("Constant", "bool", w)
      else if(w in JSIDENT) ht_put("Identifier", "ident", w)
      else ht_put(base, "text", w)
      i = j; continue }
    if(ch == "{" || ch == "}" || ch == "[" || ch == "]"){
      ht_put("Identifier", "brace", ch); i++; continue }
    if(ch == "(" || ch == ")"){ ht_put("", "paren", ch); i++; continue }
    ht_put(base, "text", ch); i++ }
  ht_shut() }

function jv_word(ch){ return ch != "" && ch ~ /[0-9A-Za-z_$]/ }

# jv_comment(): a comment, with the words that file picks out of it.
function jv_comment(t,   i, n, p, w, run){
  n = length(t); i = 1; run = ""
  while(i <= n){
    if(substr(t, i, 1) ~ /[A-Za-z]/ && !jv_word(i > 1 ? substr(t, i - 1, 1) : "")){
      p = i
      while(jv_word(substr(t, p, 1))) p++
      w = substr(t, i, p - i)
      if(w == "TODO" || w == "FIXME" || w == "XXX" || w == "TBD"){
        ht_lines("Comment", "cmnt", run); run = ""
        ht_put("Todo", "todo", w) }
      else run = run w
      i = p; continue }
    run = run substr(t, i, 1); i++ }
  ht_lines("Comment", "cmnt", run) }

# jv_string(): a string, which that file ends at the quote or at the line end,
# with the escapes in it a colour of their own.
function jv_string(s, i, n, q,   j, ch){
  j = i + 1
  ht_put("Constant", "str", q)
  while(j <= n){
    ch = substr(s, j, 1)
    if(ch == "\n") break
    if(ch == "\\"){
      ht_put("Special", "esc", substr(s, j, jv_esclen(s, j))); j += jv_esclen(s, j); continue }
    ht_put("Constant", "str", ch); j++
    if(ch == q) break }
  return j }

function jv_esclen(s, i){
  return (substr(s, i + 1, 3) ~ /^[0-9][0-9][0-9]$/) ? 4 : 2 }

# jv_template(): a string written with backquotes, which runs over line ends and
# holds an expression inside a ${ }.
function jv_template(s, i, n,   j, ch, k){
  ht_put("Constant", "tstr", "`")
  j = i + 1
  while(j <= n){
    ch = substr(s, j, 1)
    if(ch == "\n"){ ht_shut(); htout = htout "\n"; j++; continue }
    if(ch == "\\"){
      ht_put("Special", "esc", substr(s, j, jv_esclen(s, j))); j += jv_esclen(s, j); continue }
    if(ch == "$" && substr(s, j + 1, 1) == "{"){
      k = findat(s, "}", j + 2)
      if(k > 0){ ht_put("Special", "embed", substr(s, j, k - j + 1)); j = k + 1; continue } }
    ht_put("Constant", "tstr", ch); j++
    if(ch == "`") break }
  return j }

# jv_regexp(): whether the slash at i opens a regular expression, which that
# file only reads after a comma, a bracket, an equals sign or a plus.
function jv_regexp(s, i,   j, ch){
  for(j = i - 1; j >= 1; j--){
    ch = substr(s, j, 1)
    if(ch == " " || ch == "\t") continue
    return index(",(=+", ch) > 0 && substr(s, i + 1, 1) !~ /[\/*]/ }
  return 0 }

function jv_slash(s, i, n,   j, ch){
  j = i + 1
  while(j <= n){
    ch = substr(s, j, 1)
    if(ch == "\n") break
    if(ch == "\\"){ j += 2; continue }
    if(ch == "/"){
      j++
      while(substr(s, j, 1) ~ /[gimuys]/) j++
      break }
    j++ }
  ht_put("Constant", "re", substr(s, i, j - i))
  return j }

# jv_number(): the end of the number at i.
function jv_number(s, i,   j){
  j = i
  if(substr(s, j, 1) == "0" && substr(s, j + 1, 1) ~ /[xXbBoO]/){
    j += 2
    while(substr(s, j, 1) ~ /[0-9a-fA-F_]/) j++
    return j }
  while(substr(s, j, 1) ~ /[0-9_]/) j++
  if(substr(s, j, 1) == "." && substr(s, j + 1, 1) ~ /[0-9]/){
    j++
    while(substr(s, j, 1) ~ /[0-9_]/) j++ }
  if(substr(s, j, 1) ~ /[eE]/ && (substr(s, j + 1, 1) ~ /[0-9]/ ||
     (substr(s, j + 1, 1) ~ /[-+]/ && substr(s, j + 2, 1) ~ /[0-9]/))){
    j += 2
    while(substr(s, j, 1) ~ /[0-9]/) j++ }
  return j }

# --- focus -------------------------------------------------------------------
# A fence can name the lines a block is about, and everything else in it is
# dimmed: the blocks in the tree that were written by hand do that with a span of
# their own, and this is that rule written down. focus={2-4,7,1:18-,14:7-28}
# lights a whole line, a range of them, and where a colon follows the number,
# only the columns named - counted in characters of the source, from 1, so a tab
# is one column and an escaped quote is one. A line named with columns is lit
# only there, a line named without them is lit whole, and a line named nowhere is
# dimmed whole.
#
# md_focus(): read the attributes written after the language on a fence line.
# A fence is typed by hand, so anything that cannot be made sense of stops the
# build rather than going quietly out to the site.
function md_focus(spec, src,   n, i, part, a, b, parts, m){
  FOCUSN = 0
  if(spec == "") return
  if(spec !~ /^focus=\{.*\}$/) die(src ": a fence takes focus={...}, not " spec)
  spec = substr(spec, 8, length(spec) - 8)
  if(trim(spec) == "") die(src ": focus={} names no line")
  n = split(spec, parts, ",")
  for(i = 1; i <= n; i++){
    part = trim(parts[i])
    if(part ~ /^[0-9]+$/){ md_focusadd(part + 0, part + 0, 1, 0, src, part); continue }
    if(part ~ /^[0-9]+-[0-9]+$/){
      m = index(part, "-")
      a = substr(part, 1, m - 1) + 0; b = substr(part, m + 1) + 0
      md_focusadd(a, b, 1, 0, src, part); continue }
    if(part ~ /^[0-9]+:[0-9]+$/){
      m = index(part, ":")
      a = substr(part, 1, m - 1) + 0; b = substr(part, m + 1) + 0
      md_focusadd(a, a, b, b, src, part); continue }
    if(part ~ /^[0-9]+:[0-9]+-$/){
      m = index(part, ":")
      a = substr(part, 1, m - 1) + 0; b = substr(part, m + 1) + 0
      md_focusadd(a, a, b, 0, src, part); continue }
    if(part ~ /^[0-9]+:[0-9]+-[0-9]+$/){
      m = index(part, ":")
      a = substr(part, 1, m - 1) + 0
      part = substr(part, m + 1)
      m = index(part, "-")
      md_focusadd(a, a, substr(part, 1, m - 1) + 0, substr(part, m + 1) + 0, src, part); continue }
    die(src ": focus= cannot read " part) }
}

# md_focusadd(): one entry per line the term names, holding the columns it lights
# - a to of 0 reaching to the end of the line.
function md_focusadd(from, to, colfrom, colto, src, part,   ln){
  if(from < 1 || to < from) die(src ": focus= cannot read " part)
  if(colfrom < 1 || (colto != 0 && colto < colfrom)) die(src ": focus= cannot read " part)
  for(ln = from; ln <= to; ln++){
    FOCUSN++
    FOCUSLINE[FOCUSN] = ln; FOCUSFROM[FOCUSN] = colfrom; FOCUSTO[FOCUSN] = colto } }

# md_lit(): whether the column at col on line ln is one the fence named.
function md_lit(ln, col,   k){
  for(k = 1; k <= FOCUSN; k++)
    if(FOCUSLINE[k] == ln && col >= FOCUSFROM[k] &&
       (FOCUSTO[k] == 0 || col <= FOCUSTO[k])) return 1
  return 0 }

# md_focuscheck(): that every line and column the fence named is in the block,
# which is the other half of not letting a typo through.
function md_focuscheck(c, src,   k, n, lines, len){
  n = split(c, lines, "\n")
  for(k = 1; k <= FOCUSN; k++){
    if(FOCUSLINE[k] > n)
      die(src ": focus= names line " FOCUSLINE[k] " of a block that has " n)
    len = length(lines[FOCUSLINE[k]])
    # a line named whole is named whole however short it is, an empty one too
    if(FOCUSFROM[k] == 1 && FOCUSTO[k] == 0) continue
    if(FOCUSFROM[k] > len || FOCUSTO[k] > len)
      die(src ": focus= names a column past the end of line " FOCUSLINE[k]) } }

# md_dim(): the markup of a block with everything the focus set does not name
# dimmed. It is walked one source character at a time, and a span is opened in
# the output only where a character actually lands in it: a cut inside a span
# closes it and opens it again after, a span the dimming swallows whole is never
# written at all, and two spans of one colour side by side stay two, since each
# opening tag in the markup is counted and counts as an item of its own. A dim
# run that reaches the end of a line joins the one that opens the next, and the
# indent a run opens a line with is left outside it - which is how the blocks
# already in the tree are written.
function md_dim(h,   i, n, out, ln, col, cls, dim, ch, t, inst, run, want, cur){
  out = ""; ln = 1; col = 1; cls = ""; dim = 0; inst = 0; run = 0; cur = ""
  n = length(h); i = 1
  while(i <= n){
    if(substr(h, i, 12) == "<span class=" || substr(h, i, 7) == "</span>" ||
       substr(h, i, 3) == "<a " || substr(h, i, 4) == "</a>"){
      t = substr(h, i, index(substr(h, i), ">"))
      if(substr(t, 1, 5) == "<span"){ cls = substr(t, 14, length(t) - 15); inst++ }
      else if(t == "</span>"){
        cls = ""
        if(!dim && cur != ""){ out = out "</span>"; cur = "" } }
      else out = out t
      i += length(t); continue }

    ch = substr(h, i, 1)
    if(ch == "\n"){
      # a run carries on over a line end only into a line that has something on
      # it to dim: an empty line ends the run, the way the tree writes it
      if(dim && (i == n || substr(h, i + 1, 1) == "\n" || md_lit(ln + 1, 1))){
        if(cur != ""){ out = out "</span>"; cur = "" }
        dim = 0 }
      if(!dim && cur != ""){ out = out "</span>"; cur = "" }
      out = out "\n"; ln++; col = 1; i++; continue }

    t = (ch == "&") ? substr(h, i, index(substr(h, i), ";")) : ch

    # the indent a dim run opens a line with is left outside it
    if(col == 1 && !dim && !md_lit(ln, col) && (t == " " || t == "\t")){
      while((t == " " || t == "\t") && !md_lit(ln, col)){
        if(cur != ""){ out = out "</span>"; cur = "" }
        out = out t; col++; i++
        t = substr(h, i, 1) }
      continue }

    if(md_lit(ln, col)) dim = 0
    else if(!dim){ dim = 1; run++ }

    want = dim ? "Old" SUBSEP run : (cls == "" ? "" : cls SUBSEP inst)
    if(want != cur){
      if(cur != "") out = out "</span>"
      if(want != "") out = out "<span class=\"" (dim ? "Old" : cls) "\">"
      cur = want }
    out = out t; col++; i += length(t) }
  if(cur != "") out = out "</span>"
  return out }

# md_fence(): the collected fenced code as a <pre>. The word after the opening
# fence becomes the class, which is what picks up the syntax colours, and a
# clips, a bash, a c, a go or a ruby fence is coloured here rather than by hand -
# see clips(), bash(), cc(), go() and rb() above; a fence naming anything else is
# left plain. What the fence writes after that language is read by md_focus(),
# and where it names lines the rest of the block is dimmed. The contents are
# escaped here, so the source holds the code and not its markup, and the closing
# tag is glued to the last line of it so that no blank line renders at the bottom
# of the block.
function md_fence(src,   c, h){
  c = fencebuf; sub(/\n$/, "", c)
  md_out("    <pre" (fencelang == "" ? "" : " class=\"" fencelang "\"") ">")
  if(fencelang == "clips")     h = clips(c)
  else if(fencelang == "bash") h = bash(c)
  else if(fencelang == "c")    h = cc(c)
  else if(fencelang == "cpp")  h = cpp(c)
  else if(fencelang == "json") h = json(c)
  else if(fencelang == "crontab") h = crontab(c)
  else if(fencelang == "systemd") h = dosini(c)
  else if(fencelang == "debcontrol") h = debcontrol(c)
  else if(fencelang == "debchangelog") h = debchangelog(c)
  else if(fencelang == "diff")  h = diff(c)
  else if(fencelang == "sshconfig") h = sshconfig(c)
  else if(fencelang == "make")  h = make(c)
  else if(fencelang == "cmake") h = cmake(c)
  else if(fencelang == "html")  h = html(c)
  else if(fencelang == "javascript") h = javascript(c)
  else if(fencelang == "go")   h = go(c)
  else if(fencelang == "ruby") h = rb(c)
  else                         h = esc(c)
  if(FOCUSN > 0){
    if(fencelang == "") die(src ": focus= wants a fence that names a language")
    md_focuscheck(c, src)
    h = md_dim(h) }
  body = body h "</pre>\n" }

# md_heading(): one heading. Curly braces at the end of it name the id it is to
# carry, which is how pandoc spells that and how most of the others read it: an
# anchor written [text](#thing) in the prose has to have something to land on,
# and there is nothing else in the dialect that can say so. The text of the
# heading is what is left once the braces are taken off.
function md_heading(tag, text, src,   id){
  if(text ~ /\{#[A-Za-z][-0-9A-Za-z_]*\}[ \t]*$/){
    id = text
    sub(/^.*\{#/, "", id); sub(/\}[ \t]*$/, "", id)
    sub(/[ \t]*\{#[A-Za-z][-0-9A-Za-z_]*\}[ \t]*$/, "", text) }
  else if(text ~ /\{#/)
    die(src ": a heading ends with a { that names no id: " text)
  md_out("    <" tag (id == "" ? "" : " id=\"" id "\"") ">" inline(text) "</" tag ">") }

# markdown(): the body of one article, as html. Blocks are separated by blank
# lines, except inside a fence and inside a raw html element, where a blank line
# is part of the content: an html block therefore runs until the element it
# opened is closed rather than until the next blank line.
function markdown(src,   line, tag, i){
  body = ""; nbuf = 0; infence = 0; rawtag = ""; rawdepth = 0
  for(i = 1; i <= nsrc[src]; i++){
    line = source[src, i]

    if(infence){
      if(line ~ /^```/){ md_fence(src); infence = 0 } else fencebuf = fencebuf line "\n"
      continue
    }
    if(rawtag != ""){
      buf[++nbuf] = line
      if(rawtag == "!--"){ if(index(line, "-->") > 0) rawtag = "" }
      else {
        rawdepth += count(line, "<" rawtag) - count(line, "</" rawtag)
        if(rawdepth <= 0) rawtag = ""
      }
      continue
    }
    if(line ~ /^```/){
      md_flush(); infence = 1; fencebuf = ""
      fenceattr = trim(substr(line, 4))
      fencelang = fenceattr
      sub(/[ \t].*$/, "", fencelang)
      # a word is the language and anything else on the line is an attribute,
      # so that a fence may name lines without naming a language and be told so
      if(fencelang !~ /^[a-z0-9+-]+$/) fencelang = ""
      sub(/^[^ \t]*[ \t]*/, "", fenceattr)
      if(fencelang == "") fenceattr = trim(substr(line, 4))
      md_focus(trim(fenceattr), src)
      continue }
    if(line ~ /^[ \t]*$/){ md_flush(); continue }
    if(line ~ /^#### /){ md_flush(); md_heading("h4", substr(line, 6), src); continue }
    if(line ~ /^### /){  md_flush(); md_heading("h3", substr(line, 5), src); continue }

    # An html block that opens an element and does not close it on the same line
    # carries on to that closing tag, blank lines and all. The element does not
    # have to open the block: a <pre> commonly follows the comment holding the
    # plain source of what it shows, with no blank line between the two.
    if((nbuf == 0 || buf[1] ~ /^[ \t]*</) && line ~ /^[ \t]*</){
      if(line ~ /^[ \t]*<!--/ && index(line, "-->") == 0){ buf[++nbuf] = line; rawtag = "!--"; continue }
      tag = line
      sub(/^[ \t]*</, "", tag)
      sub(/[^a-zA-Z0-9].*$/, "", tag)
      if(tag != "" && !(tag in void) && count(line, "<" tag) - count(line, "</" tag) > 0){
        buf[++nbuf] = line
        rawtag = tag
        rawdepth = count(line, "<" tag) - count(line, "</" tag)
        continue
      }
    }
    buf[++nbuf] = line
  }
  if(infence) die(src ": a code fence is never closed")
  if(rawtag != "") die(src ": <" rawtag "> is never closed")
  md_flush()
  sub(/\n$/, "", body)
  return body }

# --- pages -------------------------------------------------------------------
# emit(): write one template line to out, expanding any placeholder on it. A
# scalar is substituted in place; a block (which may carry many lines) is
# spliced between whatever text sat either side of it, and when a block is empty
# and the placeholder was the whole line, the line is dropped rather than left
# behind as a blank one.
function emit(line, out,   name, p, pre, post){
  for(name in field){
    p = index(line, "@" name "@")
    if(p == 0) continue
    if(!isblock[name]){ line = litsub(line, "@" name "@", field[name]); continue }
    pre  = substr(line, 1, p-1)
    post = substr(line, p + length(name) + 2)
    if(field[name] == "" && (pre post) ~ /^[ \t]*$/) return
    printf "%s%s%s\n", pre, field[name], post > out
    return
  }
  print line > out }

# render(): expand a whole template into out. The template is closed on the way
# out so that the next article can read it again from the top.
function render(template, out,   line){
  while((getline line < template) > 0) emit(line, out)
  close(template)
  close(out) }

# read_article(): parse one articles/<slug>.md into meta[slug, key] and its
# markdown into source[slug, 1..n]. Unknown keys are an error rather than
# something silently dropped: a mistyped one would otherwise cost a description
# or a date with nothing to show for it.
function read_article(f, slug,   line, p, key, inbody){
  inbody = 0; nsrc[slug] = 0
  while((getline line < f) > 0){
    if(inbody){ source[slug, ++nsrc[slug]] = line; continue }
    if(line == "---"){ inbody = 1; continue }
    p = index(line, ":")
    if(p == 0) die(f ": front matter line is not key: value -> " line)
    key = trim(substr(line, 1, p-1))
    if(!(key in allowed)) die(f ": unknown front matter key " key)
    if((slug SUBSEP key) in meta) die(f ": " key " given twice")
    meta[slug, key] = trim(substr(line, p+1))
  }
  close(f)
  if(!inbody) die(f ": front matter is never closed by a --- line")
  if(meta[slug, "title"] == "") die(f ": no title in the front matter")
  if(meta[slug, "description"] == "") die(f ": no description in the front matter")
  if(nsrc[slug] == 0) die(f ": no body after the front matter") }

# stylesheets(): the <link> block for one article. styles.css is on every page
# and so is never listed in the front matter; the rest come from the css: line,
# in the order given there. Each resolves through the manifest to its published,
# content-addressed url.
function stylesheets(slug, indent, tail,   list, i, n, o, u){
  n = split("styles.css " meta[slug, "css"], list, /[ \t]+/)
  o = ""
  for(i = 1; i <= n; i++){
    if(list[i] == "") continue
    u = cssurl[list[i]]
    if(u == "") die(slug ": no published stylesheet for " list[i])
    o = o (o == "" ? "" : "\n") indent "<link rel=\"stylesheet\" type=\"text/css\" href=\"" u "\"" tail
  }
  return o }

# render_article(): one article page. An article without a date renders without
# the line that would have held it.
function render_article(slug,   d, out){
  out = outdir "/articles/" slug ".html"
  split("", field); split("", isblock)
  field["TITLE"]       = meta[slug, "title"]
  field["DESCRIPTION"] = meta[slug, "description"]
  field["STYLESHEETS"] = stylesheets(slug, "    ", " />");  isblock["STYLESHEETS"] = 1
  field["BODY"]        = markdown(slug);                    isblock["BODY"] = 1
  d = meta[slug, "date"]
  field["DATE"]     = (d == "") ? "" : "<p><time datetime=\"" d "\">" datetext(d) "</time></p>"
  isblock["DATE"]   = 1
  field["OG_IMAGE"] = (meta[slug, "image"] == "") ? "" \
                    : "<meta property=\"og:image\" content=\"" meta[slug, "image"] "\" />"
  isblock["OG_IMAGE"] = 1
  render(articletemplate, out) }

# render_index(): the front page. The two lists it is built from are the point
# of projects-index and articles-index: their contents and their order are the
# contents and the order of the Projects and Articles sections.
function render_index(   line, p, url, label, slug, d, o, out){
  out = outdir "/index.html"

  # projects-index: a url, whitespace, then the text to show for it. Every
  # project is somewhere else, so every one of them opens in a new tab.
  o = ""
  while((getline line < projectsfile) > 0){
    if(line ~ /^[ \t]*#/ || line !~ /[^ \t]/) continue
    p = match(line, /[ \t]/)
    if(p == 0) die("projects-index: no label after the url -> " line)
    url   = substr(line, 1, p-1)
    label = trim(substr(line, p))
    if(label == "") die("projects-index: no label after the url -> " line)
    o = o (o == "" ? "" : "\n") "\t\t\t\t<li><a href=\"" url "\" target=\"_blank\">" label "</a></li>"
  }
  close(projectsfile)
  if(o == "") die("projects-index: no projects listed")
  field["PROJECTS"] = o; isblock["PROJECTS"] = 1

  o = ""
  for(i = 0; i < NLISTED; i++){
    slug = listed[i]
    d = meta[slug, "date"]
    o = o (o == "" ? "" : "\n") "\t\t\t\t<li><a href=\"articles/" slug ".html\">" meta[slug, "title"] \
        "</a><br><time datetime=\"" d "\">" datetext(d) "</time></li>"
  }
  field["ARTICLES"] = o; isblock["ARTICLES"] = 1

  # The index page is the only one that wants index.css, so it is the only page
  # whose stylesheet block is not built from an article front matter.
  field["STYLESHEETS"] = "\t\t<link rel=\"stylesheet\" type=\"text/css\" href=\"" cssurl["styles.css"] "\">\n" \
                         "\t\t<link rel=\"stylesheet\" type=\"text/css\" href=\"" cssurl["index.css"] "\">"
  isblock["STYLESHEETS"] = 1

  render(indextemplate, out) }

