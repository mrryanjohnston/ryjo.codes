#!/bin/sh
# Generate the whole site into build/ : index.html from template/index.html plus
# projects-index and articles-index, one page per article in articles/ from
# template/article.html, and feed.rss from template/feed.rss.
#
# An article is a file articles/<slug>.md holding front matter (key: value lines
# closed by a line holding only ---) and then the body of the page in markdown.
# Everything else in articles/ - the images, the video, the stylesheets, and the
# few legacy pages that were never a standard article - is published untouched,
# as is the whole of static/.
#
# As a side effect this stages assets/ : the content-addressed copies of the
# stylesheets that the emitted pages point at.
set -eu                 # abort on any error (-e) or use of an unset variable (-u)
cd "$(dirname "$0")"    # run from the script's own dir so relative paths resolve

OUT=build

for f in template/index.html template/article.html template/feed.rss \
         projects-index articles-index; do
  [ -f "$f" ] || { echo "build.sh: missing $f" >&2; exit 1; }
done
[ -d static ] || { echo "build.sh: missing static/" >&2; exit 1; }

# has_frontmatter(): true when the file opens with front matter. Every .md in
# articles/ is expected to be an article; the check is what keeps a draft that
# is published as raw markdown (and there is one) from being read as a page.
has_frontmatter() {
  awk '
    /^---$/                     { ok = found; exit }   # front matter closed: an article
    /^[A-Za-z][A-Za-z-]*:[ \t]/ { found = 1; next }    # a key: value line
                                { exit }               # anything else: not an article
    END                         { exit !ok }
  ' "$1"
}

ARTICLE_LIST=$(mktemp)
CSS_LIST=$(mktemp)
CSS_MANIFEST=$(mktemp)
AWKPROG=$(mktemp)          # the program below, which is too big to pass as an argument
trap 'rm -f "$ARTICLE_LIST" "$CSS_LIST" "$CSS_MANIFEST" "$AWKPROG"' EXIT

rm -rf "$OUT"
mkdir -p "$OUT/articles" "$OUT/assets"

# Sort so that the build is reproducible whatever order the glob comes back in.
for f in articles/*.md; do
  if has_frontmatter "$f"; then echo "$f"; fi
done | LC_ALL=C sort > "$ARTICLE_LIST"
[ -s "$ARTICLE_LIST" ] || { echo "build.sh: no articles found in articles/" >&2; exit 1; }

# The stylesheets a page can ask for: the site-wide one, the one the index page
# adds, and whatever each article names on its css: line. Collected from what is
# actually referenced rather than globbed, so an unreferenced stylesheet never
# reaches the bucket and a typo in a css: line fails the build below.
{
  echo styles.css
  echo index.css
  while read -r f; do
    awk '/^---$/ { exit } /^css:[ \t]/ { sub(/^css:[ \t]*/, ""); print }' "$f"
  done < "$ARTICLE_LIST" | tr ' \t' '\n\n'
} | sed '/^$/d' | LC_ALL=C sort -u > "$CSS_LIST"

# Content-addressed, so that an old page held in a browser cache keeps loading
# the stylesheet it was built against, and so the published copies can be cached
# for a year without ever needing an invalidation. The source directory is kept
# in the published path: articles/ has a styles.css of its own, and flattening
# would collide it with the one at the top of the tree.
: > "$CSS_MANIFEST"
while read -r css; do
  [ -f "$css" ] || { echo "build.sh: $css is referenced but does not exist" >&2; exit 1; }
  id=$(sha256sum "$css" | cut -c1-12)
  dir=$(dirname "$css")
  base=$(basename "$css" .css)
  case "$dir" in
    .) pub="$base.$id.css" ;;
    *) pub="$dir/$base.$id.css"; mkdir -p "$OUT/assets/$dir" ;;
  esac
  cp "$css" "$OUT/assets/$pub"
  printf '%s\t/assets/%s\n' "$css" "$pub" >> "$CSS_MANIFEST"
done < "$CSS_LIST"

# The whole of the site is generated by the one awk program below. It is written
# out to a file rather than passed as an argument because it has grown past the
# length a single argument may have, and read back with -f. The heredoc is quoted
# so that the shell leaves every character of it alone.
cat > "$AWKPROG" <<'AWKPROGRAM'
#
# die(): report a build error against the generated site and stop.
function die(msg){ print "build.sh: " msg > "/dev/stderr"; exit 1 }

# trim(): strip leading and trailing whitespace from a string and return it.
function trim(s){ sub(/^[ \t]+/,"",s); sub(/[ \t]+$/,"",s); return s }

# findat(): the position of needle in s at or after from, or 0. index() only
# ever searches from the start, so the tail is searched and the offset added
# back on.
function findat(s, needle, from,   p){
  p = index(substr(s, from), needle)
  return p == 0 ? 0 : from + p - 1 }

# litsub(): replace every @token@ in s with v, literally. Not gsub, whose
# replacement string gives & a meaning of its own - an article title or a
# description is arbitrary text and may well contain one.
function litsub(s, token, v,   p, o){ o=""
  while((p=index(s, token)) > 0){
    o = o substr(s, 1, p-1) v
    s = substr(s, p + length(token))
  }
  return o s }

# esc(): escape the three characters that would otherwise be markup. "\\&" is
# how a literal & is written in a gsub replacement, where a bare & means "the
# matched text".
function esc(s){ gsub(/&/,"\\&amp;",s); gsub(/</,"\\&lt;",s); gsub(/>/,"\\&gt;",s); return s }

# count(): how many times needle occurs in s, without overlaps.
function count(s, needle,   n, p){ n = 0
  while((p = index(s, needle)) > 0){ n++; s = substr(s, p + length(needle)) }
  return n }

# --- dates -------------------------------------------------------------------
# datetext(): the human form of an ISO date, e.g. 2024-09-02 -> September 2nd,
# 2024. The ordinal suffix is th for everything except a 1, 2 or 3 in the ones
# place, and the teens take th regardless (11th, 12th, 13th).
function datetext(d,   a, day, sfx){
  checkdate(d); split(d, a, "-")
  day = a[3]+0
  sfx = "th"
  if(day % 100 < 11 || day % 100 > 13){
    if(day % 10 == 1) sfx = "st"
    else if(day % 10 == 2) sfx = "nd"
    else if(day % 10 == 3) sfx = "rd"
  }
  return month[a[2]+0] " " day sfx ", " a[1] }

# checkdate(): stop the build on anything that is not a real YYYY-MM-DD.
function checkdate(d,   a){
  if(split(d, a, "-") != 3 || a[1] !~ /^[0-9]{4}$/ || a[2] !~ /^[0-9]{2}$/ || a[3] !~ /^[0-9]{2}$/)
    die("date is not YYYY-MM-DD: " d)
  if(a[2]+0 < 1 || a[2]+0 > 12) die("date has no such month: " d)
  if(a[3]+0 < 1 || a[3]+0 > 31) die("date has no such day: " d) }

# rfc822(): the date form RSS wants, e.g. Mon, 02 Sep 2024 00:00:00 +0000. The
# weekday comes from Zeller congruence, where January and February count as
# months 13 and 14 of the year before. The time of day is midnight UTC because
# an article is dated to the day and nothing finer.
function rfc822(d,   a, y, m, q, K, J, h){
  checkdate(d); split(d, a, "-")
  y = a[1]+0; m = a[2]+0; q = a[3]+0
  if(m < 3){ m += 12; y -= 1 }
  K = y % 100; J = int(y / 100)
  h = (q + int(13*(m+1)/5) + K + int(K/4) + int(J/4) + 5*J) % 7
  return dayname[h+1] ", " a[3] " " monthabbr[a[2]+0] " " a[1] " 00:00:00 +0000" }

# --- markdown ----------------------------------------------------------------
# The dialect is deliberately small: headings, paragraphs, lists, fenced code,
# and raw html for everything it cannot say. That last part is doing real work
# here - the syntax-highlighted code blocks, the figures and the grid diagrams
# are html in the source and are passed through untouched.
#
# external(): whether a link should open in a new tab. Everything that leaves
# the site does; an anchor, a relative path and a link back to ryjo.codes do not.
function external(url){ return (url ~ /^https?:\/\//) && (url !~ /^https?:\/\/ryjo\.codes/) }

# closebracket(): the position of the ] matching the [ at from, or 0.
function closebracket(s, from,   depth, i, c){
  depth = 0
  for(i = from; i <= length(s); i++){
    c = substr(s, i, 1)
    if(c == "\\"){ i++; continue }
    if(c == "[") depth++
    else if(c == "]"){ depth--; if(depth == 0) return i } }
  return 0 }

# closeparen(): the position of the ) matching the ( at from, or 0.
function closeparen(s, from,   depth, i, c){
  depth = 0
  for(i = from; i <= length(s); i++){
    c = substr(s, i, 1)
    if(c == "(") depth++
    else if(c == ")"){ depth--; if(depth == 0) return i }
  }
  return 0 }

# inline(): convert the inline markdown in one logical line of prose to html, in
# a single left-to-right scan. The constructs nest, so this recurses: a code
# span suspends everything else (the * in a (batch*) stays a star), and a link
# label can hold a code span of its own. Raw html in the text is left alone,
# which is how a <sup> or a <br> gets into a paragraph.
function inline(s, linksonly,   o, i, n, c, nxt, p, q, txt, url){
  o = ""; n = length(s); i = 1
  while(i <= n){
    c = substr(s, i, 1)
    # Inside a code span everything is itself - a star is a star and a bracket a
    # bracket - and a link is the one exception, because a code span naming a
    # library or a flag is often the thing that links to it.
    if(!linksonly){
      # a backslash makes the next character literal
      if(c == "\\" && i < n){ o = o substr(s, i+1, 1); i += 2; continue }
      # `code`
      if(c == "`"){
        p = findat(s, "`", i+1)
        if(p > 0){ o = o "<code>" inline(substr(s, i+1, p-i-1), 1) "</code>"; i = p+1; continue }
      }
      # **bold**
      if(substr(s, i, 2) == "**"){
        p = findat(s, "**", i+2)
        if(p > 0){ o = o "<b>" inline(substr(s, i+2, p-i-2)) "</b>"; i = p+2; continue }
      }
      # *italic*, but a star opens emphasis only when something other than a space
      # follows it and closes only when something other than a space precedes it.
      # That is what leaves "the A* Algorithm" alone.
      if(c == "*"){
        nxt = substr(s, i+1, 1)
        if(nxt != "" && nxt != " " && nxt != "\t"){
          p = i
          while((p = findat(s, "*", p+1)) > 0){
            if(substr(s, p-1, 1) != " " && substr(s, p-1, 1) != "\t") break
          }
          if(p > 0){ o = o "<i>" inline(substr(s, i+1, p-i-1)) "</i>"; i = p+1; continue }
        }
      }
    }
    # ![alt](src). An image with nothing between the brackets carries no alt at
    # all, which is how the ones in the tree are written: they are equations set
    # in the middle of a sentence and there is nothing to say about them that
    # the sentence does not say already.
    if(c == "!" && substr(s, i+1, 1) == "["){
      p = closebracket(s, i+1)
      if(p > 0 && substr(s, p+1, 1) == "("){
        q = closeparen(s, p+1)
        if(q > 0){
          txt = substr(s, i+2, p-i-2)
          url = substr(s, p+2, q-p-2)
          o = o "<img src=\"" url "\"" (txt == "" ? "" : " alt=\"" esc(txt) "\"") ">"
          i = q+1; continue
        }
      }
    }
    # [text](url). The url runs to the ) that matches the ( opening it, not to
    # the first one: plenty of wikipedia urls carry a (parenthesised) suffix.
    # The ] is the one matching the [ as well, so that an image can be the text
    # of a link - a small copy of a picture standing for the whole of it.
    if(c == "["){
      p = closebracket(s, i)
      if(p > 0 && substr(s, p+1, 1) == "("){
        q = closeparen(s, p+1)
        if(q > 0){
          txt = substr(s, i+1, p-i-1)
          url = substr(s, p+2, q-p-2)
          o = o "<a href=\"" url "\"" (external(url) ? " target=\"_blank\"" : "") ">" inline(txt, linksonly) "</a>"
          i = q+1; continue
        }
      }
    }
    o = o c; i++
  }
  return o }

# htmlwrap(): greedy word-wrap to about width columns, with indent on each line.
# Breaks only at spaces that are outside an html tag, so tags stay intact; a
# chunk longer than width overflows, which is what a long url does.
function htmlwrap(s, indent, width,   out, line, tok, i, n, ch, tag){
  n = length(s); out = ""; line = ""; tok = ""; tag = 0
  for(i = 1; i <= n; i++){ ch = substr(s, i, 1)
    if(ch == "<") tag = 1; else if(ch == ">") tag = 0
    if(ch == " " && !tag){
      if(tok != ""){
        if(line == "") line = tok
        else if(length(line) + 1 + length(tok) <= width) line = line " " tok
        else { out = out indent line "\n"; line = tok }
        tok = ""
      }
    } else tok = tok ch
  }
  if(tok != ""){ if(line == "") line = tok
                 else if(length(line) + 1 + length(tok) <= width) line = line " " tok
                 else { out = out indent line "\n"; line = tok } }
  if(line != "") out = out indent line "\n"
  return out }

# md_out(): append one finished line to the body being built.
function md_out(s){ body = body s "\n" }

# md_flush(): emit the buffered block. A block whose first line opens a tag is
# html and goes out as it came in; one that opens with a > is a quotation and one
# that opens with a list marker is a list; anything else is a paragraph.
function md_flush(   i, txt){
  if(nbuf == 0) return
  if(buf[1] ~ /^[ \t]*</){ for(i = 1; i <= nbuf; i++) md_out(buf[i]) }
  else if(buf[1] ~ /^> /) md_quote()
  else if(buf[1] ~ /^(- |[0-9]+\. )/) md_list()
  else {
    txt = buf[1]
    for(i = 2; i <= nbuf; i++) txt = txt " " buf[i]
    md_out("    <p>")
    body = body htmlwrap(inline(txt), "      ", 72)
    md_out("    </p>")
  }
  nbuf = 0 }

# md_quote(): the buffered block as a quotation. The > comes off the front of
# each line and what is left is run together and wrapped the way a paragraph is,
# so a quotation can be written across as many lines as it needs.
function md_quote(   i, line, txt){
  txt = ""
  for(i = 1; i <= nbuf; i++){
    line = buf[i]
    sub(/^>[ \t]?/, "", line)
    sub(/^[ \t]+/, "", line)
    txt = (txt == "" ? line : txt " " line) }
  md_out("    <blockquote>")
  body = body htmlwrap(inline(txt), "      ", 72)
  md_out("    </blockquote>") }

# md_list(): the buffered block as a list. A line opening with a marker starts an
# item and any line after it continues the one before, so an item can be written
# across as many lines as it needs.
function md_list(   i, tag, ni, line){
  tag = (buf[1] ~ /^[0-9]+\. /) ? "ol" : "ul"
  ni = 0
  for(i = 1; i <= nbuf; i++){
    line = buf[i]
    if(line ~ /^(- |[0-9]+\. )/){ sub(/^(- |[0-9]+\. )/, "", line); item[++ni] = line }
    else { sub(/^[ \t]+/, "", line); item[ni] = item[ni] " " line }
  }
  md_out("    <" tag ">")
  for(i = 1; i <= ni; i++) md_out("      <li>" inline(item[i]) "</li>")
  md_out("    </" tag ">") }

# --- clips -------------------------------------------------------------------
# The colours in a clips block are the ones the blocks already in the tree
# carry. Those came out of vim, where *.clp is the jess filetype, so what is
# reimplemented below is syntax/jess.vim: which words are a Type and which a
# Statement, that deftemplate is neither, that a number counts only at the head
# of a symbol, and that a ?var with nothing after it on the line runs on into
# the next one. A word in neither list is left plain, which is why deftemplate
# has no colour. The one name added on top of that file is println, set in
# BEGIN with the tables.
#
# cl_shut(), cl_put(): the output, one span at a time. Two spans run together
# only when they are the same item and not merely the same colour: a keyword
# beside a concat is two Statement spans, and the ( opening a quoted list does
# not join the mark before it.
function cl_shut(){ if(clcls != ""){ clout = clout "</span>"; clcls = "" } clitem = "" }

function cl_put(cls, item, txt){
  if(cls != clcls || item != clitem){
    cl_shut()
    if(cls != "") clout = clout "<span class=\"" cls "\">"
    clcls = cls; clitem = item }
  clout = clout codeesc(txt) }

# Code escapes one character more than prose does: a quote is left alone in a
# paragraph, and written out inside a block the way the blocks already in the
# tree write it.
function codeesc(s){ s = esc(s); gsub(/"/, "\\&quot;", s); return s }

function cl_kwchar(c){ return c != "" && index(CLKWCHARS, c) > 0 }
function cl_delim(c){ return c == "" || index(CLDELIMS, c) > 0 }

function clips(s,   n, i, j, k, c, w, run, prev, t, ch){
  clout = ""; clcls = ""; clitem = ""
  n = length(s); i = 1; cldepth = 0; clstr = 0; clatom = 0; clvar = 0
  while(i <= n){
    c = substr(s, i, 1)

    # A span never crosses a line: the blocks in the tree close and reopen it.
    if(c == "\n"){ cl_shut(); clout = clout "\n"; i++; continue }

    # A ?var carried over a line end holds until a character a name cannot be
    # made of, whatever that character turns out to be.
    if(clvar){
      j = i
      while(j <= n && substr(s, j, 1) ~ /[A-Za-z0-9]/) j++
      clvar = (j > n || substr(s, j, 1) == "\n")
      if(j > i){ cl_put("Identifier", "var", substr(s, i, j - i)); i = j; continue }
      clvar = 0 }

    # A quoted atom runs to the next quote, line ends and all.
    if(clatom){
      j = i; t = ""
      while(j <= n){
        ch = substr(s, j, 1)
        if(ch == "\n") break
        if(ch == "\\" && substr(s, j + 1, 1) == "\"" ){ t = t substr(s, j, 2); j += 2; continue }
        t = t ch; j++
        if(ch == "\"") { clatom = 0; break } }
      cl_put("Identifier", "astr", t); i = j; continue }

    # A string runs to the next unescaped quote, over line ends if it has to.
    if(clstr || c == "\""){
      j = i; t = ""
      if(!clstr){ t = "\""; j = i + 1; clstr = 1 }
      while(j <= n){
        ch = substr(s, j, 1)
        if(ch == "\n") break
        if(ch == "\\" && substr(s, j + 1, 1) == "\"" ){ t = t substr(s, j, 2); j += 2; continue }
        t = t ch; j++
        if(ch == "\"") { clstr = 0; break } }
      cl_put("Constant", "str", t); i = j; continue }

    # A comment runs to the end of the line, quotes and parens and all.
    if(c == ";"){
      j = index(substr(s, i), "\n")
      t = (j == 0 ? substr(s, i) : substr(s, i, j - 1))
      cl_put("Comment", "com", t); i += length(t); continue }

    # Parens. A ) with nothing open is the error the tree paints it as.
    if(c == "(" || c == ")"){
      while(i <= n){
        c = substr(s, i, 1)
        if(c == "("){ cldepth++; cl_put("Special", "par", "(") }
        else if(c == ")"){
          if(cldepth > 0){ cldepth--; cl_put("Special", "par", ")") }
          else cl_put("Error", "err", ")") }
        else break
        i++ }
      continue }

    # A ?var, but only where a symbol has not already started: inside a list
    # the ? in the middle of a?b belongs to the symbol and is not a variable.
    if(c == "?"){
      j = i + 1
      while(j <= n && substr(s, j, 1) ~ /[A-Za-z0-9]/) j++
      clvar = (j > n || substr(s, j, 1) == "\n")
      cl_put("Identifier", "var", substr(s, i, j - i)); i = j; continue }

    if(c == SQ){
      if(substr(s, i + 1, 1) == "\""){
        clatom = 1; j = i + 2; t = substr(s, i, 2)
        while(j <= n){
          ch = substr(s, j, 1)
          if(ch == "\n") break
          if(ch == "\\" && substr(s, j + 1, 1) == "\"" ){ t = t substr(s, j, 2); j += 2; continue }
          t = t ch; j++
          if(ch == "\"") { clatom = 0; break } }
        cl_put("Identifier", "astr", t); i = j; continue }
      cl_put("Special", "amark", SQ); i++
      j = i
      while(j <= n && substr(s, j, 1) !~ /[ \t\n()]/ && substr(s, j, 1) != SQ) j++
      if(j > i){ cl_put("Identifier", "atom", substr(s, i, j - i)); i = j }
      continue }

    if(c == " " || c == "\t"){
      if(substr(s, i, 3) ~ /^[ \t]\.[ \t]$/){
        cl_put("Statement", "cat", substr(s, i, 3)); i += 3; continue }
      cl_put("", "", c); i++; continue }

    # A keyword is a whole word: the character before it cannot be one a word
    # is made of, or this is the tail of something longer.
    prev = (i > 1 ? substr(s, i - 1, 1) : "")
    j = i
    while(j <= n && cl_kwchar(substr(s, j, 1))) j++
    w = substr(s, i, j - i)
    if(w != "" && !cl_kwchar(prev)){
      if(w in CLKEY){ cl_put("Type", "key", w); i = j; continue }
      if((w in CLFUNC) || w ~ /^c[ad]+r$/){ cl_put("Statement", "fun", w); i = j; continue } }

    if(c == "*" && substr(s, i) ~ /^\*[a-zA-Z_][a-zA-Z_0-9-]*\*/){
      j = i + 1
      while(j <= n && substr(s, j, 1) != "*") j++
      cl_put("Type", "spc", substr(s, i, j - i + 1)); i = j + 1; continue }
    if(c == "#" && substr(s, i) ~ /^#(x[0-9a-fA-F]+|o[0-7]+|b[01]+)/){
      j = i + 2
      while(j <= n && substr(s, j, 1) ~ /[0-9a-fA-F]/) j++
      cl_put("Type", "spc", substr(s, i, j - i)); i = j; continue }

    # |a bar symbol| holds together whatever is between the bars, but only on
    # the one line: a bar left unclosed is just a character.
    if(cldepth > 0 && c == "|"){
      j = i + 2
      while(j <= n && substr(s, j, 1) != "|" && substr(s, j, 1) != "\n") j++
      if(j <= n && substr(s, j, 1) == "|"){
        cl_put("Special", "bar", substr(s, i, j - i + 1)); i = j + 1; continue } }

    # Inside a list a run of non-delimiters is one symbol, and only a number at
    # the very head of it is picked out. Outside a list there is no such symbol,
    # so a number anywhere in the run is one.
    if(cldepth > 0){
      j = i
      while(j <= n && !cl_delim(substr(s, j, 1)) && substr(s, j, 1) != "\n") j++
      run = substr(s, i, j - i)
      # A delimiter with no rule of its own - a comma, a backquote - is not part
      # of a symbol and stands for itself.
      if(run == ""){ cl_put("", "", c); i++; continue }
      if(run ~ /^[0-9]/){
        k = 1
        while(k <= length(run) && substr(run, k, 1) ~ /[0-9]/) k++
        cl_put("Constant", "num", substr(run, 1, k - 1))
        cl_put("", "", substr(run, k)) }
      else cl_put("", "", run)
      i = j; continue }

    if(c ~ /[0-9]/){
      j = i
      while(j <= n && substr(s, j, 1) ~ /[0-9]/) j++
      cl_put("Constant", "num", substr(s, i, j - i)); i = j; continue }

    cl_put("", "", c); i++ }
  cl_shut()
  return clout }

# --- bash --------------------------------------------------------------------
# The colours in a bash block are the ones the blocks already in the tree carry.
# Those came out of vim, so what is reimplemented below is syntax/sh.vim reading
# a file it has decided is bash: which words are a Statement, that the quotes
# around a string are not the colour of the string, that the text inside a $( )
# is a Special because it is a command and not an argument, that an operator is
# only an operator inside something (the pipe between two commands at the top of
# a block is left plain), and that a } with nothing open is the error the tree
# paints it as. Left out of that file is what no block on the site reaches: the
# word lists vim keeps for ksh and posix rather than for bash, the variable
# names it knows only inside a $( ), and the pattern it reads after an = at the
# head of a word. A block holding something that is not shell at all still comes
# out the way vim reads it as shell, which is what the tree already has.
#
# bs_shut(), bs_put(): the output, one span at a time, the way cl_shut() and
# cl_put() do it for clips - a span ends where the colour ends or the item does,
# so that an option in a $( ) breaks the run of Special around it in two.
function bs_shut(){ if(bscls != ""){ bsout = bsout "</span>"; bscls = "" } bsitem = "" }

function bs_put(cls, item, txt){
  if(cls != bscls || item != bsitem){
    bs_shut()
    if(cls != "") bsout = bsout "<span class=\"" cls "\">"
    bscls = cls; bsitem = item }
  bsout = bsout codeesc(txt) }

# bs_lines(): the same, for text that runs over a line end - which a span may
# not do, so the line end closes it and the next line opens it again.
function bs_lines(cls, item, txt,   p){
  while((p = index(txt, "\n")) > 0){
    if(p > 1) bs_put(cls, item, substr(txt, 1, p - 1))
    bs_shut(); bsout = bsout "\n"
    txt = substr(txt, p + 1) }
  if(txt != "") bs_put(cls, item, txt) }

# The context stack: what the block is inside of at this point. A context
# carries the colour of the text that is nothing smaller than itself - plain at
# the top of a block, a Special inside a $( ), a Constant inside a string - and
# it is what the next closing bracket closes. A context that says nothing about
# colour, "-" below, keeps the colour of the one it was opened inside: the body
# of an if is not a colour, it is only somewhere a then is not an error.
function bs_open(kind, cls, item){
  bsd++
  bskind[bsd]  = kind
  bsbcls[bsd]  = (cls == "-" ? bsbcls[bsd-1]  : cls)
  bsbitem[bsd] = (cls == "-" ? bsbitem[bsd-1] : item) }

function bs_pop(){ if(bsd > 0) bsd-- }

# bs_depth(): the depth of the innermost context of either kind, or 0. Closing
# one closes everything left open inside it: a fi that never came does not keep
# the ) from ending the substitution the if was opened in.
function bs_depth(k1, k2,   d){
  for(d = bsd; d > 0; d--)
    if(bskind[d] == k1 || (k2 != "" && bskind[d] == k2)) return d
  return 0 }

function bs_in(kind){ return bs_depth(kind, "") > 0 }

# bs_bracket(): the depth of the innermost context a bracket opened, which is
# the only one a closing bracket can be closing: the )) of an arithmetic does
# not reach past a $( ) opened inside it.
function bs_bracket(   d, k){
  for(d = bsd; d > 0; d--){
    k = bskind[d]
    if(k == "sub" || k == "par" || k == "bq"  || k == "ari" || k == "dpr" ||
       k == "arb" || k == "tst" || k == "dbr" || k == "idx" || k == "fun" ||
       k == "exp") return d }
  return 0 }

# bs_txt(): text that is nothing but what it is inside of.
function bs_txt(txt){ bs_put(bsbcls[bsd], bsbitem[bsd], txt) }

# bs_eol(): where the line holding i ends. bs_bol(): whether i opens a line.
# bs_sep(): whether what comes before i is whitespace, which is what a comment
# and an option both need in front of them.
function bs_eol(s, i,   p){ p = index(substr(s, i), "\n"); return p == 0 ? length(s) + 1 : i + p - 1 }
function bs_bol(s, i){ return i == 1 || substr(s, i - 1, 1) == "\n" }
function bs_sep(s, i,   c){ c = (i > 1 ? substr(s, i - 1, 1) : "\n"); return c == " " || c == "\t" || c == "\n" }

# bs_word(): the word starting at i, or "" where a word does not start there -
# the character before one cannot be a character a word is made of, or this is
# the tail of something longer and not a word of its own.
function bs_word(s, i, n,   j){
  if(i > 1 && substr(s, i - 1, 1) ~ /[-:A-Za-z0-9_]/) return ""
  j = i
  while(j <= n && substr(s, j, 1) ~ /[-:A-Za-z0-9_]/) j++
  return substr(s, i, j - i) }

# bs_test(): whether the innermost thing open is one vim reads a word opening
# with a - inside of as a test operator rather than as an option - a [ ], but
# the body of a loop or a conditional as well, where -i is the colour of -eq and
# not of --output. The body of a function is not one, and neither is anything
# holding a command: a $( ) inside a [ ] holds options again.
function bs_test(   d){
  for(d = bsd; d > 0; d--){
    if(bskind[d] == "tst" || bskind[d] == "dbr" || bskind[d] == "dpr" ||
       bskind[d] == "if"  || bskind[d] == "whl" || bskind[d] == "for" ||
       bskind[d] == "do") return 1
    if(bskind[d] == "sub" || bskind[d] == "par" || bskind[d] == "bq" ||
       bskind[d] == "ari" || bskind[d] == "fun" || bskind[d] == "exp" ||
       bskind[d] == "cas") return 0 }
  return 0 }

# bs_escape(): the backslash at i and whatever it makes literal, and where that
# ends. Which of three things it is decides nothing about the colour and
# everything about where the span holding it ends: a backslash before
# punctuation, one opening a control sequence, and one before anything else are
# three items to vim, so two of them side by side are two spans.
#
# At the top of a block only the first of the three is a Special and a backslash
# carrying a line on to the next one is an operator; inside anything else - a
# string, a $( ), an echo, the body of a function - all three are, and the one
# before a line end is just more of what it is inside. In a here document whose
# word was quoted nothing is escaped at all.
function bs_escape(s, i, literal,   c, t, len){
  c = substr(s, i + 1, 1)
  if(literal || c == "" || c == "\n"){
    if(c == "\n" && bsd == 0) bs_put("Statement", "wrap", "\\")
    else bs_txt("\\")
    return i + 1 }
  t = "esc"; len = 2
  if(index("\\\"`$()#" SQ, c) > 0) t = "dqs"
  else if(index("abefnrtv", c) > 0) t = "spc"
  else if(c == "c" && substr(s, i + 2, 1) != "" && substr(s, i + 2, 1) != "\""){ t = "spc"; len = 3 }
  else if(c == "x" && substr(s, i + 2, 2) ~ /^[0-9A-Fa-f][0-9A-Fa-f]$/){ t = "spc"; len = 4 }
  else if(substr(s, i + 1, 3) ~ /^[0-7][0-7][0-7]$/){ t = "spc"; len = 4 }
  if(bsd == 0 && t != "dqs"){ bs_txt("\\"); return i + 1 }
  bs_put("Special", t, substr(s, i, len)); return i + len }

# bs_dollar(): the $ construct at i and where it ends, or i itself when what
# follows the $ is not one, which leaves the $ to be text. The brackets of a
# ${ } are the same colour as the name inside them but not the same item, which
# is why they come out as spans of their own.
function bs_dollar(s, i, n,   c, j, t){
  c = substr(s, i + 1, 1)
  if(c == "(" && substr(s, i + 2, 1) == "("){
    bs_put("PreProc", "sub", "$(("); bs_open("ari", "Special", "sub"); return i + 3 }
  if(c == "("){
    bs_put("PreProc", "sub", "$("); bs_open("sub", "Special", "sub"); return i + 2 }
  if(c == "["){
    bs_put("PreProc", "sub", "$["); bs_open("arb", "Special", "sub"); return i + 2 }
  if(c == "{"){
    t = "${"; j = i + 2
    if(substr(s, j, 1) == "#" || substr(s, j, 1) == "!"){ t = t substr(s, j, 1); j++ }
    bs_put("PreProc", "drf", t); bs_open("der", "PreProc", "var"); return j }
  if(c ~ /[A-Za-z_]/){
    j = i + 1
    while(j <= n && substr(s, j, 1) ~ /[A-Za-z0-9_]/) j++
    bs_put("PreProc", "der", substr(s, i, j - i)); return j }
  if(c == SQ || c == "\""){
    bs_put("Statement", "quo", substr(s, i, 2))
    bs_open(c == SQ ? "esq" : "dq", "Constant", "str"); return i + 2 }
  if(c ~ /[0-9]/ || index("-#*@!?$", c) > 0){
    bs_put("PreProc", "der", substr(s, i, 2)); return i + 2 }
  return i }

# bs_here(): the << that opens a here document, the word naming it, and where
# that ends; i itself when no word follows, which leaves the << a redirection.
# A quoted or backslashed word is one the shell does not expand, and a <<- is
# one whose closing word may be indented.
function bs_here(s, i, n,   j, q, w){
  j = i + 2
  if(substr(s, j, 1) == "-"){ bsheretab = 1; j++ } else bsheretab = 0
  while(substr(s, j, 1) == " " || substr(s, j, 1) == "\t") j++
  bsherexp = 1
  q = substr(s, j, 1)
  if(q == SQ || q == "\""){
    bsherexp = 0
    j++
    while(j <= n && substr(s, j, 1) != q && substr(s, j, 1) != "\n") j++
    if(substr(s, j, 1) != q) return i
    w = substr(s, i, j - i + 1)
    bshere = substr(w, index(w, q) + 1, length(w) - index(w, q) - 1)
    bs_put("Statement", "here", w); bs_open("here", "Constant", "str"); return j + 1 }
  if(q == "\\"){ bsherexp = 0; j++ }
  bshere = ""
  while(j <= n && substr(s, j, 1) !~ /[ \t\n|>]/){ bshere = bshere substr(s, j, 1); j++ }
  if(bshere == "") return i
  bs_put("Statement", "here", substr(s, i, j - i)); bs_open("here", "Constant", "str"); return j }

# bs_redir(): how many characters of redirection are at i, or 0. The digit in
# front of one is a number and the & behind it an operator, each of them a thing
# of its own: only the > or the < is the redirection.
function bs_redir(s, i,   c, j){
  c = substr(s, i, 1)
  if(c != "<" && c != ">") return 0
  j = (substr(s, i + 1, 1) == c) ? i + 2 : i + 1
  # A >&2 is one redirection, but the > of a 2>&1 is only the >: the digit in
  # front of it is a number of its own and what follows it goes with that.
  if(substr(s, j, 1) == "&" && substr(s, j + 1, 1) ~ /[-0-9]/ &&
     (i == 1 || substr(s, i - 1, 1) !~ /[0-9]/)) j += 2
  return j - i }

# bs_func(): a function definition at i - a name, its brackets and the { that
# opens its body, which vim colours as one thing however many lines it is
# written over - and where it ends; i itself when this is not one. The body is
# a context so that the } closing it is the same colour as the name.
function bs_func(s, i, n, named,   j, k){
  j = i
  if(!named){ while(substr(s, j, 1) == " " || substr(s, j, 1) == "\t") j++ }
  k = j
  while(j <= n && substr(s, j, 1) ~ /[-A-Za-z0-9_:]/) j++
  if(j == k) return i
  while(substr(s, j, 1) == " " || substr(s, j, 1) == "\t") j++
  if(substr(s, j, 1) == "("){
    j++
    while(substr(s, j, 1) == " " || substr(s, j, 1) == "\t") j++
    if(substr(s, j, 1) != ")") return i
    j++ }
  else if(!named) return i
  while(j <= n && substr(s, j, 1) ~ /[ \t\n]/) j++
  if(substr(s, j, 1) != "{") return i
  bs_lines("Identifier", "fun", substr(s, i, j - i + 1))
  bs_open("fun", "-", "")
  return j + 1 }

# bs_link(): the last thing vim does to a block, after the colours are in it: a
# url written out in the open becomes a link. The url runs to whitespace, to a
# quote or a bracket, or to the markup of the span it sits in, and a . , ; : or
# } right at the end of it is punctuation and not part of the link.
function bs_link(h,   o, p, j, e, c){
  o = ""
  while((p = bs_urlat(h)) > 0){
    o = o substr(h, 1, p - 1)
    h = substr(h, p)
    j = index(h, "://") + 3
    e = 0
    while(e == 0){
      c = substr(h, j, 1)
      if(c == "" || c ~ /[ \t\n\\"<>]/ || c == SQ) e = j
      else if(substr(h, j, 4) == "&gt;" || substr(h, j, 4) == "&lt;" ||
              substr(h, j, 6) == "&quot;") e = j
      else if(index(".,;:}", c) > 0){
        c = substr(h, j + 1, 1)
        if(c == "" || c ~ /[ \t\n]/) e = j }
      if(e == 0) j++ }
    o = o "<a href=\"" substr(h, 1, e - 1) "\">" substr(h, 1, e - 1) "</a>"
    h = substr(h, e) }
  return o h }

# bs_urlat(): where the next url in h starts, or 0.
function bs_urlat(h,   p, q){
  p = index(h, "http://"); q = index(h, "https://")
  if(p == 0) return q
  if(q == 0) return p
  return p < q ? p : q }

# bash(): one bash block, as the spans that colour it.
function bash(s,   n, i, j, d, c, k, t, w, fkey){
  bsout = ""; bscls = ""; bsitem = ""
  bsd = 0; bskind[0] = "top"; bsbcls[0] = ""; bsbitem[0] = ""
  bshere = ""; bsherexp = 0; bsheretab = 0; fkey = 0
  n = length(s); i = 1
  while(i <= n){
    c = substr(s, i, 1); k = bskind[bsd]

    # The payload of a here document holds until the line holding the word that
    # opened it, which is a redirection again and not part of the string.
    if(k == "here" && bs_bol(s, i)){
      j = bs_eol(s, i); t = substr(s, i, j - i); w = t
      if(bsheretab) sub(/^\t+/, "", w)
      if(w == bshere){
        bs_put("Statement", "here", t); bshere = ""; bs_pop(); i = j; continue } }

    # A span never crosses a line end: it closes the span, it ends an echo, and
    # it is where the payload of a here document named on it begins.
    if(c == "\n"){
      if(k == "ech" || k == "set"){ bs_pop(); k = bskind[bsd] }
      bs_shut(); bsout = bsout "\n"; i++
      continue }

    # Inside a single quoted string there is nothing but the string.
    if(k == "sq"){
      if(c == SQ){ bs_put("Statement", "quo", c); bs_pop() } else bs_txt(c)
      i++; continue }

    # Inside a double quoted string, a here document, or the tail of an echo -
    # all three of which are a string as far as the colours go - what a shell
    # would still read in there is picked out and the rest is the string. An
    # echo ends where its command does, before whatever ended it.
    if(k == "dq" || k == "esq" || k == "here" || k == "ech"){
      if((k == "dq" && c == "\"") || (k == "esq" && c == SQ)){
        bs_put("Statement", "quo", c); bs_pop(); i++; continue }
      if(k == "ech" && (index("<>;&|()`", c) > 0 || (c == "#" && bs_sep(s, i)))){ bs_pop(); continue }
      if(c == "\\"){ i = bs_escape(s, i, (k == "here" && !bsherexp)); continue }
      if(c == "$" && k != "esq" && (k != "here" || bsherexp)){
        j = bs_dollar(s, i, n); if(j > i){ i = j; continue } }
      if(k != "here" && k != "esq" && c == "`"){
        bs_put("Special", "sub", c); bs_open("bq", "Special", "sub"); i++; continue }
      if(k == "ech" && (c == "\"" || c == SQ)){
        bs_put("Statement", "quo", c)
        bs_open(c == "\"" ? "dq" : "sq", "Constant", "str"); i++; continue }
      bs_txt(c); i++; continue }

    # Inside a ${ }, everything is the dereference up to the word operator, and
    # the pattern the operator takes is plain text.
    if(k == "der" || k == "drp" || k == "drs"){
      if(c == "}"){ bs_put("PreProc", "drf", c); bs_pop(); i++; continue }
      if(c == "[" && k == "der"){
        bs_put("PreProc", "idx", c); bs_open("idx", "", ""); i++; continue }
      if(k == "der"){
        t = ""
        if(c == ":" && index("-=?+", substr(s, i + 1, 1)) > 0) t = substr(s, i, 2)
        else if(index("-=?+", c) > 0) t = c
        else if(index("#%,^/", c) > 0){ t = c; if(substr(s, i + 1, 1) == c) t = c c }
        else if(c == ":"){                     # an offset, which runs to the }
          j = i
          while(j <= n && substr(s, j, 1) != "}" && substr(s, j, 1) != "\n") j++
          bs_put("Statement", "drop", substr(s, i, j - i)); i = j; continue }
        if(t != ""){
          bs_put("Statement", "drop", t); bs_pop()
          # Only a replacement goes on to take a second pattern, so only there
          # is the / between the two of them an operator and not text.
          bs_open(substr(t, 1, 1) == "/" ? "drs" : "drp", "", "")
          i += length(t); continue } }
      if(k == "drs" && c == "/"){ bs_put("Statement", "drsl", c); i++; continue }
      if(c == "$"){ j = bs_dollar(s, i, n); if(j > i){ i = j; continue } }
      bs_txt(c); i++; continue }

    # The label a case branch opens with is only text as far as the colours go:
    # the bar between two patterns and the number in one are left plain, and the
    # ) that ends the label is the one thing in it that is not.
    if(k == "lbl"){
      if(bs_word(s, i, n) == "esac"){ bs_pop(); continue }
      if(c == ")" || c == "("){
        bs_put("Statement", "case", c)
        if(c == ")") bs_pop()
        i++; continue }
      if(c == "\"" || c == SQ){
        bs_put("Statement", "quo", c)
        bs_open(c == "\"" ? "dq" : "sq", "Constant", "str"); i++; continue }
      if(c == "`"){ bs_put("Special", "sub", c); bs_open("bq", "Special", "sub"); i++; continue }
      if(c == "$"){ j = bs_dollar(s, i, n); if(j > i){ i = j; continue } }
      if(c == "#" && bs_sep(s, i)){
        j = bs_eol(s, i); bs_put("Comment", "com", substr(s, i, j - i)); i = j; continue }
      bs_txt(c); i++; continue }

    # A function definition opens a line, unless the word function opened it.
    if(bs_bol(s, i) && (j = bs_func(s, i, n, 0)) > i){ i = j; continue }
    if(fkey && (j = bs_func(s, i, n, 1)) > i){ fkey = 0; i = j; continue }

    # A set or an unset takes the rest of its line with it, which is why the
    # space between one and its first option is not the colour of the space
    # after any other command.
    if(k == "set" && index(";|)#", c) > 0){ bs_pop(); continue }

    # A comment runs to the end of the line. It has to open a word: the # in
    # a${x#y} is not one, and neither is the one in a#b.
    if(c == "#" && (bs_sep(s, i) || (k == "bq" && substr(s, i - 1, 1) == "`"))){
      j = bs_eol(s, i)
      if(k == "bq" && (d = index(substr(s, i, j - i), "`")) > 0) j = i + d - 1
      bs_put("Comment", "com", substr(s, i, j - i)); i = j; continue }

    if(c == "\\"){ i = bs_escape(s, i, 0); continue }

    if(c == "\"" || c == SQ){
      bs_put("Statement", "quo", c)
      bs_open(c == "\"" ? "dq" : "sq", "Constant", "str"); i++; continue }

    # A ` opens a substitution and the next one closes it. Both of them and the
    # command between them are the one item, which is how vim writes it.
    if(c == "`"){
      bs_put("Special", "sub", c)
      if(k == "bq") bs_pop(); else bs_open("bq", "Special", "sub")
      i++; continue }

    if(c == "$"){
      j = bs_dollar(s, i, n)
      if(j > i){ i = j; continue }
      bs_txt(c); i++; continue }

    if(c == "<" && substr(s, i + 1, 1) == "<" && substr(s, i + 2, 1) != "<"){
      j = bs_here(s, i, n); if(j > i){ i = j; continue } }

    # A test operator is not an option: -z inside a [ ] is a Statement where -r
    # outside one is a Special.
    if(bs_test() && index("=!<>", c) > 0){
      t = substr(s, i, 2)
      if(t == "==" || t == "!=" || t == "<=" || t == ">=" || t == "=~"){
        bs_put("Statement", "tst", t); i += 2
        if(t == "=~"){
          while(substr(s, i, 1) == " " || substr(s, i, 1) == "\t"){ bs_txt(substr(s, i, 1)); i++ }
          j = i
          while(j <= n && substr(s, j, 1) !~ /[ \t\n]/) j++
          if(j > i){ bs_put("Constant", "pat", substr(s, i, j - i)); i = j } }
        continue }
      bs_put("Statement", "tst", c); i++; continue }

    if((j = bs_redir(s, i)) > 0){
      bs_put("Statement", "red", substr(s, i, j)); i += j; continue }

    # Brackets. Which one it is decides the colour of it and of what it holds: a
    # $( ) and a ( ) hold a command, a [ ] a test, a { } a group, and one that
    # closes nothing at all is an error.
    if(c == "("){
      if(substr(s, i + 1, 1) == "("){
        bs_put("Special", "dpr", "(("); bs_open("dpr", "", ""); i += 2; continue }
      bs_put("PreProc", "sub", "("); bs_open("par", "Special", "sub"); i++; continue }

    if(c == ")"){
      d = bs_bracket(); t = (d > 0 ? bskind[d] : "")
      if((t == "ari" || t == "dpr") && substr(s, i + 1, 1) == ")"){
        bsd = d - 1
        if(t == "ari") bs_put("PreProc", "sub", "))"); else bs_put("Special", "dpr", "))")
        i += 2; continue }
      if(t == "sub" || t == "par"){ bsd = d - 1; bs_put("PreProc", "sub", c); i++; continue }
      bs_put("Error", "err", c); i++; continue }

    if(c == "["){
      if(substr(s, i + 1, 1) == "["){
        bs_put("Special", "dbr", "[["); bs_open("dbr", "", ""); i += 2; continue }
      bs_put("Statement", "brk", c); bs_open("tst", "", ""); i++; continue }

    if(c == "]"){
      d = bs_bracket(); t = (d > 0 ? bskind[d] : "")
      if(t == "dbr" && substr(s, i + 1, 1) == "]"){
        bsd = d - 1; bs_put("Special", "dbr", "]]"); i += 2; continue }
      if(t == "idx"){ bsd = d - 1; bs_put("PreProc", "idx", c); i++; continue }
      if(t == "tst" || t == "arb"){
        bsd = d - 1
        if(t == "arb") bs_put("PreProc", "sub", c); else bs_put("Statement", "brk", c)
        i++; continue }
      bs_txt(c); i++; continue }

    if(c == "{"){ bs_put("Special", "exp", c); bs_open("exp", "-", ""); i++; continue }

    if(c == "}"){
      d = bs_bracket()
      if(d > 0 && (bskind[d] == "fun" || bskind[d] == "exp")){
        t = bskind[d]; bsd = d - 1
        if(t == "fun") bs_put("Identifier", "fun", c); else bs_put("Special", "exp", c) }
      else bs_put("Error", "err", c)
      i++; continue }

    # An = is an operator wherever it stands on its own - the name in front of
    # one and the = itself are the assignment and are handled with the words.
    if(c == "=" || (index("-/*+%", c) > 0 && substr(s, i + 1, 1) == "=")){
      if(c != "=") t = substr(s, i, 2)
      else t = (substr(s, i + 1, 1) == "=" ? "==" : "=")
      bs_put("Statement", "opr", t); i += length(t); continue }

    # The others are only operators inside something: the pipe joining two
    # commands at the top of a block is left plain, and the ;; of a case that
    # never opened is an error.
    if(index(";|&!", c) > 0){
      t = c
      if(substr(s, i + 1, 1) == c) t = c c
      if(c == ";" && bs_in("cas") && substr(s, i + length(t), 1) == "&") t = t "&"
      if(bsd > 0) bs_put("Statement", "opr", t)
      else if(t == ";;") bs_put("Error", "err", t)
      else bs_txt(t)
      if(c == ";" && bs_in("cas")) bs_open("lbl", "-", "")
      i += length(t); continue }

    # A word opening with a - is three different things. Inside a [ ] it is the
    # operator the test is made of, a - in front of digits is the sign of a
    # number, and anywhere else it is an option.
    if(c == "-" && bs_test()){
      j = i + 1
      while(j <= n && substr(s, j, 1) ~ /[A-Za-z]/) j++
      t = substr(s, i + 1, j - i - 1)
      if(length(t) == 1 || t ~ /^(nt|ot|ef|eq|ne|lt|le|gt|ge)$/){
        bs_put("Statement", "tst", substr(s, i, j - i)); i = j; continue } }

    # A number is a whole word of digits: the 1 of 1m is part of the word and
    # not a number of its own.
    if((c ~ /[0-9]/ || (c == "-" && substr(s, i + 1, 1) ~ /[0-9]/) ||
        (c == "-" && substr(s, i + 1, 1) == "." && substr(s, i + 2, 1) ~ /[0-9]/)) &&
       (i == 1 || substr(s, i - 1, 1) !~ /[-:A-Za-z0-9_]/)){
      j = i
      if(c == "-"){ j++; if(substr(s, j, 1) == ".") j++ }
      while(j <= n && substr(s, j, 1) ~ /[0-9]/) j++
      if(substr(s, j, 1) !~ /[-:A-Za-z_]/){
        if(substr(s, j, 1) == "#") j++
        bs_put("Constant", "num", substr(s, i, j - i)); i = j; continue } }

    # An option is a word opening with a - or a +, but only where whitespace
    # came before it, which is what leaves the - in a file name alone.
    if((c == "-" || c == "+") && bs_sep(s, i) && substr(s, i - 1, 1) != "\n"){
      j = i + 1
      if(c == "-" && substr(s, j, 1) == "-"){
        j++
        while(j <= n && substr(s, j, 1) !~ /[ \t\n$=`|);"]/ && substr(s, j, 1) != SQ) j++ }
      else while(j <= n && substr(s, j, 1) ~ /[-_A-Za-z#@]/) j++
      if(j > i + 1){ bs_put("Special", "opt", substr(s, i, j - i)); i = j; continue } }

    # A keyword is a whole word, and which words are keywords is the list vim
    # holds for bash. A word that closes something it never opened is an error;
    # the words that open something carry the whitespace after them, the way
    # vim colours the space that ends an if as part of the if.
    w = bs_word(s, i, n)
    if(w != ""){
      j = i + length(w)
      t = substr(s, j, 1)
      d = (t == " " || t == "\t") ? 1 : 0
      fkey = 0
      if(w == "if" || w == "while" || w == "until"){
        bs_put("Statement", "cond", substr(s, i, length(w) + d))
        if(w == "if") bs_open("if", "-", ""); else bs_open("whl", "Statement", "whl")
        i = j + d; continue }
      if(w == "for" || w == "select"){
        bs_put("Statement", "cond", w); bs_open("for", "-", ""); i = j; continue }
      if(w == "case"){
        bs_put("Statement", "cond", w); bs_open("cas", "-", ""); i = j; continue }
      if(w == "do"){
        if((d = bs_depth("whl", "for")) > 0) bsd = d - 1
        bs_put("Statement", "cond", w); bs_open("do", "-", ""); i = j; continue }
      if(w == "done" || w == "fi" || w == "esac"){
        d = bs_depth(w == "done" ? "do" : (w == "fi" ? "if" : "cas"), "")
        if(d > 0){ bsd = d - 1; bs_put("Statement", "cond", w) }
        else bs_put("Error", "err", w)
        i = j; continue }
      if(w == "then" || w == "else" || w == "elif"){
        bs_put(bs_in("if") ? "Statement" : "Error", bs_in("if") ? "cond" : "err", w)
        i = j; continue }
      if(w == "in"){
        d = bs_depth("for", "")
        if(d > 0 && d > bs_depth("cas", "")){ bsd = d - 1; bs_put("Statement", "cond", w) }
        else if(bs_in("cas")){ bs_put("Statement", "cond", w); bs_open("lbl", "-", "") }
        else bs_put("Error", "err", w)
        i = j; continue }
      if(w == "function"){ bs_put("Identifier", "fky", w); fkey = 1; i = j; continue }
      if(w == "set" || w == "unset"){
        bs_put("Statement", "cmd", w); bs_open("set", "Identifier", "set"); i = j; continue }
      if(w == "echo" || w == "print"){
        bs_put("Statement", "cmd", w); bs_open("ech", "Constant", "ech"); i = j; continue }
      if(w in BSSTMT){ bs_put("Statement", "cmd", w); i = j; continue }
      # A word an = follows is the name of a variable being given a value. The
      # = itself is plain: it is part of neither the name nor what follows.
      if(t == "=" && w ~ /^[A-Za-z_][A-Za-z0-9_]*$/){
        bs_put("Identifier", "var", w)
        bs_put("", "", "="); j++
        if(substr(s, j, 1) == "("){
          bs_put("PreProc", "sub", "("); bs_open("par", "", ""); i = j + 1; continue }
        if(substr(s, j, 1) ~ /[A-Za-z_]/){
          d = j
          while(j <= n && substr(s, j, 1) ~ /[A-Za-z0-9_]/) j++
          bs_put("", "", substr(s, d, j - d)) }
        i = j; continue }
      bs_txt(w); i = j; continue }

    bs_txt(c); i++ }
  bs_shut()
  return bs_link(bsout) }

# --- c -----------------------------------------------------------------------
# The colours in a c block are the ones the blocks already in the tree carry.
# Those came out of vim, so what is reimplemented below is syntax/c.vim: which
# words are a Type and which a Statement, that const is a Type because that file
# paints a storage class as one, that a character constant holding an escape is
# a Special where one holding a plain character is a Constant, that a printf
# format inside a string has a colour of its own, that the zero at the head of
# an octal number is the PreProc it is deliberately linked to, that a comment
# comes out as three spans - the /*, what it holds and the */ - because the mark
# at either end is an item of its own, and that what a preprocessor line holds
# is the colour of the line unless vim knows it for something else. Left out of
# that file is what no block on the site reaches: the c++ words it adds for a
# .cpp, the doxygen comments and the gnu extensions it only loads when asked,
# and the <% and the :> that c99 lets a bracket be written as.
#
# cc_shut(), cc_put(): the output, one span at a time, the way cl_put() does it
# for clips - a span ends where the colour ends or the item does, so that the /*
# opening a comment breaks the run of Comment around it.
function cc_shut(){ if(cccls != ""){ ccout = ccout "</span>"; cccls = "" } ccitem = "" }

function cc_put(cls, item, txt){
  if(cls != cccls || item != ccitem){
    cc_shut()
    if(cls != "") ccout = ccout "<span class=\"" cls "\">"
    cccls = cls; ccitem = item }
  ccout = ccout codeesc(txt) }

# cc_lines(): the same, for text that runs over a line end - which a span may
# not do, so the line end closes it and the next line opens it again.
function cc_lines(cls, item, txt,   p){
  while((p = index(txt, "\n")) > 0){
    if(p > 1) cc_put(cls, item, substr(txt, 1, p - 1))
    cc_shut(); ccout = ccout "\n"
    txt = substr(txt, p + 1) }
  if(txt != "") cc_put(cls, item, txt) }

# cc_txt(): text with no colour of its own, which is no colour at all until a
# preprocessor line is open - vim reads one as a region, so a name in there that
# it does not know is the colour of the line rather than plain.
function cc_txt(txt){ cc_put(ccbg, ccbg == "" ? "" : "pre", txt) }

function cc_kwchar(ch){ return ch != "" && ch ~ /[0-9A-Za-z_]/ }

# cc_frame(): the innermost ( [ or ? still open, or 0 when none is. The blocks a
# { opens inside one of those are looked past: that file keeps the end of the
# outer one through them, so a ) closes its ( with a { left open in between.
function cc_frame(   k){
  k = ccdepth
  while(k > 0 && ccstack[k] == "{") k--
  return k }

# cc_eol(): the position of the line end at or after i, or one past the text.
function cc_eol(s, i,   p){ p = index(substr(s, i), "\n"); return p == 0 ? length(s) + 1 : i + p - 1 }

# cc_bol(): whether nothing but whitespace comes before i on its line, which is
# where vim looks for the # that opens a preprocessor line.
function cc_bol(s, i,   j, ch){
  for(j = i - 1; j >= 1; j--){
    ch = substr(s, j, 1)
    if(ch == "\n") return 1
    if(ch != " " && ch != "\t") return 0 }
  return 1 }

# cc_ctext(): what a comment holds, as its spans - one span, except that vim
# picks the words TODO, FIXME and XXX out of it and gives them a colour of their
# own, that it marks the slash of a /* written inside a comment that is already
# open, and that no span carries over a line end.
function cc_ctext(item, txt,   i, n, p, ch, w, run){
  n = length(txt); i = 1; run = ""
  while(i <= n){
    ch = substr(txt, i, 1)
    if(ch == "/" && substr(txt, i + 1, 1) == "*" && item == "body"){
      cc_lines("Comment", item, run); run = ""
      cc_put("Error", "err", "/"); i++; continue }
    if(ch ~ /[A-Za-z_]/ && !cc_kwchar(i > 1 ? substr(txt, i - 1, 1) : "")){
      p = i
      while(cc_kwchar(substr(txt, p, 1))) p++
      w = substr(txt, i, p - i)
      if(w in CCTODO && item != "out"){
        cc_lines("Comment", item, run); run = ""
        cc_put("Todo", "todo", w) }
      else run = run w
      i = p; continue }
    run = run ch; i++ }
  cc_lines("Comment", item, run) }

# cc_esclen(): the length of the escape at the backslash at i. An escape written
# in hex runs as far as the hex does, one written in octal three digits at most,
# and a backslash at a line end stands on its own.
function cc_esclen(s, i,   j, ch){
  ch = substr(s, i + 1, 1)
  if(ch == "" || ch == "\n") return 1
  if(ch == "x" && substr(s, i + 2, 1) ~ /[0-9a-fA-F]/){
    j = i + 2
    while(substr(s, j, 1) ~ /[0-9a-fA-F]/) j++
    return j - i }
  if(ch ~ /[0-7]/){
    j = i + 1
    while(j - i <= 3 && substr(s, j, 1) ~ /[0-7]/) j++
    return j - i }
  return 2 }

# cc_char(): the length of the character constant at i, or 0 when the quote
# there opens nothing vim reads as one - a lone quote is left plain, the way
# that file leaves it. CCCHAR comes back with the colour: a plain character is a
# Constant and one written as an escape a Special.
function cc_char(s, i,   ch, j, d){
  ch = substr(s, i + 1, 1)
  if(ch == "" || ch == "\n" || ch == SQ) return 0
  if(ch != "\\"){
    if(substr(s, i + 2, 1) != SQ) return 0
    CCCHAR = "Constant"; return 3 }
  ch = substr(s, i + 2, 1)
  if(ch == "") return 0
  if(index(CCESC, ch) > 0 && substr(s, i + 3, 1) == SQ){ CCCHAR = "Special"; return 4 }
  if(ch ~ /[0-7]/){
    j = i + 2; d = 0
    while(d < 3 && substr(s, j, 1) ~ /[0-7]/){ j++; d++ } }
  else if(ch == "x" && substr(s, i + 3, 1) ~ /[0-9a-fA-F]/){
    j = i + 3; d = 0
    while(d < 2 && substr(s, j, 1) ~ /[0-9a-fA-F]/){ j++; d++ } }
  else return 0
  if(substr(s, j, 1) != SQ) return 0
  CCCHAR = "Special"; return j - i + 1 }

# cc_format(): the length of the printf format at i, or 0. The one that file
# matches, less the %1$ form that names an argument by its number.
function cc_format(s, i,   j, ch){
  if(substr(s, i + 1, 1) == "%") return 2
  j = i + 1
  while((ch = substr(s, j, 1)) != "" && index("-+ #0" SQ, ch) > 0) j++
  if(substr(s, j, 1) == "*") j++
  else while(substr(s, j, 1) ~ /[0-9]/) j++
  if(substr(s, j, 1) == "."){
    j++
    if(substr(s, j, 1) == "*") j++
    else while(substr(s, j, 1) ~ /[0-9]/) j++ }
  if(substr(s, j, 2) == "ll" || substr(s, j, 2) == "hh") j += 2
  else if((ch = substr(s, j, 1)) != "" && index("hlLjzt", ch) > 0) j++
  ch = substr(s, j, 1)
  if(ch != "" && index("aAbdiuoxXDOUfFeEgGcCsSpn", ch) > 0) return j - i + 1
  return 0 }

# cc_string(): the string at i, as its spans, and the position after it. What it
# holds is the colour of the string, except an escape and a printf format, which
# have colours of their own. A string left unclosed ends where the line does,
# unless the line is ended with a backslash: that carries it on to the next one.
function cc_string(s, i, n,   j, ch, t){
  cc_put("Constant", "str", "\"")
  j = i + 1
  while(j <= n){
    ch = substr(s, j, 1)
    if(ch == "\n") break
    if(ch == "\\"){
      t = cc_esclen(s, j)
      cc_put("Special", "esc", substr(s, j, t)); j += t
      if(t == 1 && substr(s, j, 1) == "\n"){ cc_shut(); ccout = ccout "\n"; j++ }
      continue }
    if(ch == "%" && (t = cc_format(s, j)) > 0){
      cc_put("Special", "fmt", substr(s, j, t)); j += t; continue }
    cc_put("Constant", "str", ch); j++
    if(ch == "\"") break }
  return j }

# cc_isuffix(): the end of the u and l suffix on a whole number at j, which
# that file writes as u=l{0,2} or ll=u and reads without regard to case.
function cc_isuffix(s, j,   k){
  k = j
  if(tolower(substr(s, k, 1)) == "u"){
    k++
    while(tolower(substr(s, k, 1)) == "l" && k - j <= 2) k++
    return k }
  while(tolower(substr(s, k, 1)) == "l" && k - j < 2) k++
  if(k > j && tolower(substr(s, k, 1)) == "u") k++
  return k }

# cc_fsuffix(): the end of the f or l suffix on a fractional number at j.
function cc_fsuffix(s, j){ return tolower(substr(s, j, 1)) ~ /^[fl]$/ ? j + 1 : j }

# cc_digits(): the end of the run of digits of the given kind that starts at j -
# the kind is a string, because awk reads a regular expression written out in an
# argument as a test against the line it is reading.
function cc_digits(s, j, kind,   k){
  k = j
  while(substr(s, k, 1) ~ kind) k++
  return k }

# cc_number(): the number at i, as its spans, and the position after it. Which
# shapes count is that file: a whole number wants a word end after it, so 3ld is
# no number at all and comes out plain, where a fraction written with a dot does
# not, which is how the 1.0 of 1.0iF is a number and the rest of it is not. The
# zero at the head of a number written in octal is picked out, which is the one
# colour in that file that is not the colour of the number, and a digit an octal
# number cannot hold makes the whole of it the error that file marks.
function cc_number(s, i, n,   j, k, oct, dotted, run){
  j = i; dotted = 0; oct = 0
  if(substr(s, i, 1) == "0" && tolower(substr(s, i + 1, 1)) == "x"){
    j = cc_digits(s, i + 2, "[0-9a-fA-F]")
    if(substr(s, j, 1) == "." || tolower(substr(s, j, 1)) == "p"){
      if(substr(s, j, 1) == ".") j = cc_digits(s, j + 1, "[0-9a-fA-F]")
      if(tolower(substr(s, j, 1)) == "p"){
        k = j + 1
        if(substr(s, k, 1) ~ /[-+]/) k++
        if(substr(s, k, 1) ~ /[0-9]/) j = cc_fsuffix(s, cc_digits(s, k, "[0-9]")) } }
    else j = cc_isuffix(s, j) }
  else if(substr(s, i, 1) == "."){
    j = cc_digits(s, i + 1, "[0-9]")
    j = cc_exponent(s, j)
    j = cc_fsuffix(s, j) }
  else {
    j = cc_digits(s, i, "[0-9]")
    if(substr(s, j, 1) == "."){
      dotted = 1
      j = cc_exponent(s, cc_digits(s, j + 1, "[0-9]"))
      j = cc_fsuffix(s, j) }
    else if(cc_exponent(s, j) > j) j = cc_fsuffix(s, cc_exponent(s, j))
    else {
      run = substr(s, i, j - i)
      if(substr(s, i, 1) == "0" && j - i > 1){
        if(run ~ /[89]/){ cc_put("Error", "err", run); return j }
        oct = 1 }
      j = cc_isuffix(s, j) } }
  if(!dotted && cc_kwchar(substr(s, j, 1))){
    j = cc_digits(s, j, "[0-9A-Za-z_]")
    cc_txt(substr(s, i, j - i))
    return j }
  if(oct){
    cc_put("PreProc", "zero", "0")
    cc_put("Constant", "num", substr(s, i + 1, j - i - 1))
    return j }
  cc_put("Constant", "num", substr(s, i, j - i))
  return j }

# cc_exponent(): the end of the e+00 an exponent is written with at j, or j.
function cc_exponent(s, j,   k){
  if(tolower(substr(s, j, 1)) != "e") return j
  k = j + 1
  if(substr(s, k, 1) ~ /[-+]/) k++
  if(substr(s, k, 1) !~ /[0-9]/) return j
  return cc_digits(s, k, "[0-9]") }

# cc_label(): the length of the name at i when it is the label of a goto, which
# vim reads as a name inside a match that takes in the colon after it and has no
# colour of its own - so on a preprocessor line, where everything else is the
# colour of the line, that colon comes out plain.
# is a name at the head of a line or straight after a semicolon with a single
# colon after it, and 0 when it is not - a digit after that colon makes it the
# width of a bit field instead, which vim leaves plain - though not inside a
# bracket or on a preprocessor line, neither of which is somewhere that file
# looks for a bit field.
function cc_label(s, i,   j, k, ch){
  if(ccdepth > 0 && ccstack[ccdepth] == "?") return 0
  for(j = i - 1; j >= 1; j--){
    ch = substr(s, j, 1)
    if(ch == "\n" || ch == ";") break
    if(ch != " " && ch != "\t") return 0 }
  j = i
  while(cc_kwchar(substr(s, j, 1))) j++
  k = j
  while(substr(s, k, 1) == " " || substr(s, k, 1) == "\t") k++
  if(substr(s, k, 1) != ":" || substr(s, k + 1, 1) == ":") return 0
  k++
  while(substr(s, k, 1) == " " || substr(s, k, 1) == "\t") k++
  if(ccdepth == 0 && ccbg == "" && substr(s, k, 1) ~ /[1-9]/) return 0
  return j - i }

# cc_ifoff(): where the arm that the #if at i turns off ends, or 0 when the line
# at i turns nothing off. vim paints an arm it can see is never taken as a
# comment: for an #if 0 that is the arm the line opens, and for an #if 1 it is
# the other one, which is noted in CCOFF against the #else that opens it and
# comes back as -1, there being nothing to paint here. A number that is not all
# zeros is the arm that is taken, and one that is turns the arm off - and only
# where nothing but a comment, an && after a zero or an || after a number
# follows it, since anything else may yet decide the condition. CCDIG comes back
# with the end of that number, which is where the colour of the directive
# stops.
function cc_ifoff(s, i,   line, rest, e, j, w, depth, val){
  line = substr(s, i, cc_eol(s, i) - i)
  if(line ~ /^#[ \t]*if[ \t]+0+[ \t]*($|\/\/|\/\*|&)/) val = 0
  else if(line ~ /^#[ \t]*if[ \t]+0*[1-9][0-9]*[ \t]*($|\/\/|\/\*|\|)/) val = 1
  else return 0
  rest = line
  sub(/^#[ \t]*if[ \t]+[0-9]+/, "", rest)
  CCDIG = i + length(line) - length(rest)
  depth = 0
  j = cc_eol(s, i) + 1
  while(j <= length(s)){
    e = cc_eol(s, j)
    w = substr(s, j, e - j)
    sub(/^[ \t]*/, "", w)
    if(w ~ /^#[ \t]*(if|ifdef|ifndef)([^0-9A-Za-z_]|$)/) depth++
    else if(w ~ /^#[ \t]*endif([^0-9A-Za-z_]|$)/){
      if(depth == 0) return val == 0 ? j : -1
      depth-- }
    else if(depth == 0 && w ~ /^#[ \t]*(else|elif)([^0-9A-Za-z_]|$)/){
      if(val == 0) return j
      CCOFF[j] = cc_ifend(s, j)
      return -1 }
    j = e + 1 }
  return val == 0 ? length(s) + 1 : -1 }

# cc_ifend(): where the #endif that closes the conditional the line at i belongs
# to begins, or one past the end of the block when nothing closes it.
function cc_ifend(s, i,   e, j, w, depth){
  depth = 0
  j = cc_eol(s, i) + 1
  while(j <= length(s)){
    e = cc_eol(s, j)
    w = substr(s, j, e - j)
    sub(/^[ \t]*/, "", w)
    if(w ~ /^#[ \t]*(if|ifdef|ifndef)([^0-9A-Za-z_]|$)/) depth++
    else if(w ~ /^#[ \t]*endif([^0-9A-Za-z_]|$)/){
      if(depth == 0) return j
      depth-- }
    j = e + 1 }
  return length(s) + 1 }

# cc(): one c block, as the spans that colour it.
function cc(s,   n, i, j, k, ch, w, prev, t){
  ccout = ""; cccls = ""; ccitem = ""
  ccbg = ""; ccmode = ""; ccbgend = 0; ccdepth = 0; ccheld = 0; split("", CCOFF)
  n = length(s); i = 1
  while(i <= n){
    ch = substr(s, i, 1)
    prev = (i > 1 ? substr(s, i - 1, 1) : "")
    if(ccbgend > 0 && i > ccbgend){ ccbg = ""; ccmode = ""; ccbgend = 0; ccdepth = ccheld }

    # no span carries over a line end.
    if(ch == "\n"){ cc_shut(); ccout = ccout "\n"; i++; continue }

    # a comment: // to the end of the line, or /* to the */ that closes it, and
    # if nothing does, to the end of the block. A */ with no comment open is the
    # error vim marks it as.
    if(ch == "/" && substr(s, i + 1, 1) == "/"){
      j = cc_eol(s, i)
      cc_ctext("line", substr(s, i, j - i)); i = j; continue }
    if(ch == "/" && substr(s, i + 1, 1) == "*"){
      cc_put("Comment", "start", "/*")
      j = findat(s, "*/", i + 2)
      if(j == 0){ cc_ctext("body", substr(s, i + 2)); i = n + 1; continue }
      cc_ctext("body", substr(s, i + 2, j - i - 2))
      cc_put("Comment", "end", "*/")
      i = j + 2; continue }
    if(ch == "*" && substr(s, i + 1, 1) == "/"){
      cc_put("Error", "err", "*/"); i += 2; continue }

    # a preprocessor line, of which that file has four shapes. An #else and an
    # #endif are the word and nothing more, so what follows one is ordinary
    # code. An include names a file, and that is a string: the directive and the
    # space after it are one colour and the file another. An #if 0 turns off
    # everything up to the #else or the #endif that ends it, and vim paints what
    # it turns off as a comment. Every other directive opens a region that runs
    # to the end of the line - over a line ended with a backslash to the end of
    # the next one as well - and what that region holds keeps a colour of its
    # own only where vim knows it: for a #define that is a string, a number, a
    # comment or a name it has a word for, and for a condition the words are
    # left out, so only a string, a number or a comment shows through. The rest
    # is the colour of the line, which is what cc_txt() lays down while ccbg is
    # set. The brackets such a line opens are its own - that file keeps a second
    # pair for them, which ends where the line does - so the count is put aside
    # while one is open and taken up again after it.
    if(ch == "#" && cc_bol(s, i)){
      if(i in CCOFF){
        j = i + 1
        while(substr(s, j, 1) == " " || substr(s, j, 1) == "\t") j++
        while(substr(s, j, 1) ~ /[A-Za-z_]/) j++
        while(substr(s, j, 1) == " " || substr(s, j, 1) == "\t") j++
        cc_put("PreProc", "pre", substr(s, i, j - i))
        cc_ctext("out", substr(s, j, CCOFF[i] - j))
        i = CCOFF[i]; continue }
      j = cc_ifoff(s, i)
      if(j != 0){
        cc_put("PreProc", "pre", substr(s, i, CCDIG - i))
        i = CCDIG
        if(j > 0){ cc_ctext("out", substr(s, i, j - i)); i = j }
        continue }
      j = i + 1
      while(substr(s, j, 1) == " " || substr(s, j, 1) == "\t") j++
      while(substr(s, j, 1) ~ /[A-Za-z_]/) j++
      w = substr(s, i + 1, j - i - 1)
      sub(/^[ \t]+/, "", w)
      if(!(w in CCPRE)){ cc_txt(ch); i++; continue }
      if(CCPRE[w] == "match"){
        cc_put("PreProc", "pre", substr(s, i, j - i)); i = j; continue }
      k = j
      while(substr(s, k, 1) == " " || substr(s, k, 1) == "\t") k++
      # an include is only one when it names a file: the form that leaves the
      # name to a macro is not a shape that file has a rule for.
      if(CCPRE[w] == "include" && substr(s, k, 1) != "\"" && substr(s, k, 1) != "<"){
        cc_txt(ch); i++; continue }
      j = k
      cc_put("PreProc", "pre", substr(s, i, j - i))
      i = j
      if(CCPRE[w] == "include"){
        if(substr(s, i, 1) == "<"){
          j = findat(s, ">", i)
          if(j > 0 && j < cc_eol(s, i)){
            cc_put("Constant", "incl", substr(s, i, j - i + 1)); i = j + 1 } }
        continue }
      ccbg = "PreProc"
      ccmode = CCPRE[w]
      ccheld = ccdepth
      ccdepth = 0
      ccbgend = cc_eol(s, i) - 1
      while(substr(s, ccbgend, 1) == "\\") ccbgend = cc_eol(s, ccbgend + 2) - 1
      continue }

    if(ch == "\""){ i = cc_string(s, i, n); continue }

    if(ch == SQ && (t = cc_char(s, i)) > 0){
      cc_put(CCCHAR, "char", substr(s, i, t)); i += t; continue }

    if((ch ~ /[0-9]/ && !cc_kwchar(prev)) ||
       (ch == "." && substr(s, i + 1, 1) ~ /[0-9]/)){ i = cc_number(s, i, n); continue }

    if(ch ~ /[A-Za-z_]/){
      j = i
      while(cc_kwchar(substr(s, j, 1))) j++
      w = substr(s, i, j - i)
      if(ccmode == "cond" && ccdepth == 0) cc_txt(w)
      else if(CCPP && w in CPPPRE)   cc_put("PreProc", "module", w)
      else if(CCPP && w in CPPSTMT)  cc_put("Statement", "stmt", w)
      else if(CCPP && w in CPPTYPE)  cc_put("Type", "type", w)
      else if(CCPP && w in CPPCONST) cc_put("Constant", "const", w)
      else if(w in CCTYPE)  cc_put("Type", "type", w)
      else if(w in CCSTMT)  cc_put("Statement", "stmt", w)
      else if(w in CCCONST) cc_put("Constant", "const", w)
      else if(ccmode != "cond" && cc_label(s, i) > 0){
        cc_put("Statement", "label", w)
        k = j
        while(substr(s, k, 1) == " " || substr(s, k, 1) == "\t") k++
        cc_put("", "", substr(s, j, k - j + 1))
        j = k + 1 }
      else                  cc_txt(w)
      i = j; continue }

    # a bracket in the wrong place, which vim paints as an error: a ) or a ]
    # that closes nothing, a { inside either, and a ; inside a [ ] - or inside
    # the ? : that file reads as a region of the same kind, which is why the
    # question mark is pushed here along with them and the colon takes it off
    # again. A { inside one of them opens a block that file has a name of its
    # own for and paints as an error at both ends, and the } that closes it is
    # no end to what it sits in. A } that closes nothing ends every one of them
    # at once, which is the end the ( and the [ are written with in that file -
    # except on a preprocessor line, where they are the other pair that file
    # keeps, which have no such end, so a } inside one of those is an error like
    # the rest. A { or a } outside them all opens and closes a block and is no
    # error at all.
    if(ch == "?" || ch == "(" || ch == "["){ ccstack[++ccdepth] = ch; cc_txt(ch); i++; continue }
    if(ch == ":" || ch == ")" || ch == "]"){
      k = cc_frame()
      if(k > 0 && ccstack[k] == (ch == ":" ? "?" : (ch == ")" ? "(" : "["))){
        ccdepth = k - 1; cc_txt(ch) }
      else if(ch == ":") cc_txt(ch)
      else cc_put("Error", "err", ch)
      i++; continue }
    if(ch == "{"){
      if(ccdepth == 0 || CCPP) cc_txt(ch)
      else { ccstack[++ccdepth] = ch; cc_put("Error", "err", ch) }
      i++; continue }
    if(ch == "}"){
      if(ccdepth == 0 || CCPP) cc_txt(ch)
      else if(ccstack[ccdepth] == "{"){ ccdepth--; cc_put("Error", "err", ch) }
      else if(ccbg != "" || ccstack[ccdepth] == "?") cc_put("Error", "err", ch)
      else { ccdepth = 0; cc_txt(ch) }
      i++; continue }
    if(ch == ";"){
      k = cc_frame()
      if(k > 0 && ccstack[k] != "("){ cc_put("Error", "err", ch); i++; continue } }

    cc_txt(ch); i++ }
  cc_shut()
  return bs_link(ccout) }

# --- c++ ----------------------------------------------------------------------
# syntax/cpp.vim is syntax/c.vim with a list of words on top of it, so cpp() is
# cc() with those words switched on: the ones it paints as a statement, which
# are the accesses and the casts as well, the ones it paints as a type, which
# take in the modifiers and the storage classes, and the two it paints as a
# constant, and the two c++20 gives to a module, which are the colour of an
# include. Where that file is read the c way of marking a brace inside a paren
# is off, a c++ writing one there on purpose, so cc() leaves those alone. Left out of it is what no block on the
# site reaches: the raw strings, the module words c++20 adds, and the suffixes
# it lets a number carry.
function cpp(s,   out){
  CCPP = 1
  out = cc(s)
  CCPP = 0
  return out }

# --- go ----------------------------------------------------------------------
# The colours in a go block are the ones the blocks already in the tree carry.
# Those came out of vim, so what is reimplemented below is syntax/go.vim as it
# reads a file with none of its options set - which is how it comes: the words
# it paints, the escapes and the printf verbs it picks out of a string, and the
# shapes it will read as a number. A comment there is one span and not the three
# a c comment comes out as, since that file marks neither end of it; the minus
# in front of a number is never part of it, the word boundary it wants at the
# end of one is why 12ab is no number at all, and a string left unclosed runs on
# to the next line, all of which is that file and not this one. Left out of it
# is everything behind an option nobody has set: the operators, the functions
# and the fields it will paint when asked, the errors it will mark over a stray
# space, and the tags it will pick out of a //go:generate line.
#
# go_shut(), go_put(): the output, one span at a time, the way cl_put() does it
# for clips - a span ends where the colour ends or the item does.
function go_shut(){ if(gocls != ""){ goout = goout "</span>"; gocls = "" } goitem = "" }

function go_put(cls, item, txt){
  if(cls != gocls || item != goitem){
    go_shut()
    if(cls != "") goout = goout "<span class=\"" cls "\">"
    gocls = cls; goitem = item }
  goout = goout codeesc(txt) }

# go_lines(): the same, for text that runs over a line end - which a span may
# not do, so the line end closes it and the next line opens it again.
function go_lines(cls, item, txt,   p){
  while((p = index(txt, "\n")) > 0){
    if(p > 1) go_put(cls, item, substr(txt, 1, p - 1))
    go_shut(); goout = goout "\n"
    txt = substr(txt, p + 1) }
  if(txt != "") go_put(cls, item, txt) }

function go_kwchar(ch){ return ch != "" && ch ~ /[0-9A-Za-z_]/ }

# go_decl(): whether the import, var or const that ends at j is one that file
# paints. It holds those three words for the inside of a declaration and reaches
# them by two matches, one for the ( that opens a list and one for a single
# declaration: either way a space and then something has to follow the word.
function go_decl(s, j){
  return substr(s, j, 1) == " " && substr(s, j + 1, 1) != "" && substr(s, j + 1, 1) != "\n" }

function go_eol(s, i,   p){ p = index(substr(s, i), "\n"); return p == 0 ? length(s) + 1 : i + p - 1 }

# go_ctext(): what a comment holds, as its spans - one span, except for the
# words that file picks out of it, and except at a line end.
function go_ctext(item, txt,   i, n, p, ch, w, run){
  n = length(txt); i = 1; run = ""
  while(i <= n){
    ch = substr(txt, i, 1)
    if(ch ~ /[A-Za-z_]/ && !go_kwchar(i > 1 ? substr(txt, i - 1, 1) : "")){
      p = i
      while(go_kwchar(substr(txt, p, 1))) p++
      w = substr(txt, i, p - i)
      if(w in GOTODO){
        go_lines("Comment", item, run); run = ""
        go_put("Todo", "todo", w) }
      else run = run w
      i = p; continue }
    run = run ch; i++ }
  go_lines("Comment", item, run) }

# go_esclen(): the length of the escape at the backslash at i. GOESC comes back
# with its colour - an escape that file does not know is an error there - and
# GOESCKIND with which of its matches read it, so that an escape written in
# octal beside one written in hex stays two spans and does not run into one.
function go_esclen(s, i,   ch, d, want){
  GOESC = "Special"; GOESCKIND = "err"
  ch = substr(s, i + 1, 1)
  if(ch == "" || ch == "\n"){ GOESC = "Error"; return 1 }
  if(ch ~ /[0-7]/){
    if(substr(s, i + 2, 1) ~ /[0-7]/ && substr(s, i + 3, 1) ~ /[0-7]/){ GOESCKIND = "oct"; return 4 }
    GOESC = "Error"; return 2 }
  if(ch == "x" || ch == "u" || ch == "U"){
    want = (ch == "x" ? 2 : (ch == "u" ? 4 : 8))
    d = 0
    while(d < want && substr(s, i + 2 + d, 1) ~ /[0-9a-fA-F]/) d++
    if(d == want){ GOESCKIND = ch; return 2 + want }
    GOESC = "Error"; return 2 }
  if(index(GOESCC, ch) > 0){ GOESCKIND = "c"; return 2 }
  GOESC = "Error"; return 2 }

# go_fmtlen(): the length of the printf verb at the per cent sign at i, or 0.
function go_fmtlen(s, i,   j, ch){
  j = i + 1
  while((ch = substr(s, j, 1)) != "" && index("-#0 +", ch) > 0) j++
  j = go_fmtwidth(s, j)
  if(substr(s, j, 1) == "."){ j = go_fmtwidth(s, j + 1) }
  j = go_fmtindex(s, j)
  ch = substr(s, j, 1)
  if(ch != "" && index("vTtbcdoqxXUeEfFgGspw", ch) > 0) return j - i + 1
  return 0 }

# go_fmtwidth(): the width or the precision of a printf verb at j, which is a
# number, a star, or a star with the argument it takes named in front of it.
function go_fmtwidth(s, j,   k){
  k = go_fmtindex(s, j)
  if(substr(s, k, 1) == "*") return k + 1
  while(substr(s, j, 1) ~ /[0-9]/) j++
  return j }

# go_fmtindex(): past the [1] that names an argument by its number at j, or j.
function go_fmtindex(s, j,   k){
  if(substr(s, j, 1) != "[") return j
  k = j + 1
  while(substr(s, k, 1) ~ /[0-9]/) k++
  if(k > j + 1 && substr(s, k, 1) == "]") return k + 1
  return j }

# go_digits(): the end of the run of digits of the given kind at j, where a
# single underscore between two of them is part of the run.
function go_digits(s, j, kind,   k){
  k = j
  while(substr(s, k, 1) ~ kind ||
        (substr(s, k, 1) == "_" && substr(s, k - 1, 1) ~ kind && substr(s, k + 1, 1) ~ kind)) k++
  return k }

# go_number(): the end of the number at i, or 0 when what is there is no number
# that file will read. Every shape it has a match for is tried and the longest
# that comes off is the answer, which is what leaves 0xFF.foo a hex number with
# a field after it and 12ab no number at all - that file wants a word end after
# one, except after the dot of a number written as 1. with nothing following. A
# number written as .5 wants a space or a tab in front of it, so one at the head
# of a line is only the 5.
function go_number(s, i, n, prev,   j, k, e, best, ch){
  best = 0
  ch = substr(s, i, 1)
  if(ch == "."){
    if(prev != " " && prev != "\t") return 0
    if(substr(s, i + 1, 1) !~ /[0-9]/) return 0
    j = go_digits(s, i + 1, "[0-9]")
    best = go_best(s, j, best)
    return go_best(s, go_exp(s, j, "[eE]"), best) }
  if(ch !~ /[0-9]/) return 0
  if(ch == "0" && substr(s, i + 1, 1) ~ /[xX]/){
    j = go_digits(s, i + 2, "[0-9a-fA-F]")
    if(j > i + 2) best = go_best(s, j, best)
    k = j
    if(substr(s, k, 1) == ".") k = go_digits(s, k + 1, "[0-9a-fA-F]")
    if(k > i + 2){
      e = go_exp(s, k, "[pP]")
      if(e > k) best = go_best(s, e, best) }
    return best }
  if(ch == "0" && substr(s, i + 1, 1) ~ /[oObB]/){
    j = go_digits(s, i + 2, substr(s, i + 1, 1) ~ /[oO]/ ? "[0-7]" : "[01]")
    return j > i + 2 ? go_best(s, j, best) : 0 }
  j = go_digits(s, i, "[0-9]")
  best = go_best(s, j, best)
  best = go_best(s, go_exp(s, j, "[eE]"), best)
  if(substr(s, j, 1) == "."){
    k = go_digits(s, j + 1, "[0-9]")
    if(k > j + 1){
      best = go_best(s, k, best)
      best = go_best(s, go_exp(s, k, "[eE]"), best) }
    # a number written as 1. is one whatever follows the dot
    if(best < j + 1) best = (substr(s, j + 1, 1) == "i" ? j + 2 : j + 1) }
  return best }

# go_best(): the end of a number that runs to j once the i of an imaginary one
# is taken in, or the best so far when a word carries on from there.
function go_best(s, j, best,   k){
  k = (substr(s, j, 1) == "i") ? j + 1 : j
  if(go_kwchar(substr(s, k, 1))) return best
  return k > best ? k : best }

# go_exp(): past the exponent at j, written with the letter given, or j.
function go_exp(s, j, letter,   k){
  if(substr(s, j, 1) !~ letter) return j
  k = j + 1
  if(substr(s, k, 1) ~ /[-+]/) k++
  if(substr(s, k, 1) !~ /[0-9]/) return j
  return go_digits(s, k, "[0-9]") }

# go_pkgcomment(): where the comment that ends at j reaches when it is the one
# written over a package line - which that file reads as a comment of its own,
# ending where the word package begins, so that the newline and the indent in
# front of it are the colour of the comment as well. A run of line comments
# counts only while each line after the first opens with the slashes itself. 0
# when the comment at j is not one of those.
function go_pkgcomment(s, j, lines,   k){
  k = j
  if(lines) while(substr(s, k, 1) == "\n" && substr(s, k + 1, 2) == "//") k = go_eol(s, k + 1)
  if(substr(s, k, 1) != "\n") return 0
  k++
  while(substr(s, k, 1) == " " || substr(s, k, 1) == "\t") k++
  if(substr(s, k, 7) != "package") return 0
  if(go_kwchar(substr(s, k + 7, 1))) return 0
  return k }

# go_string(): the string at i, as its spans, and the position after it. The
# quotes are the colour of the string, and an escape and a printf verb inside it
# have colours of their own - a verb only inside a string, since that file does
# not look for one inside a character. A string left unclosed runs on to the
# next line, the way that file reads one.
function go_string(s, i, n, quote, escapes, verbs,   j, ch, t){
  go_put("Constant", "str", quote)
  j = i + 1
  while(j <= n){
    ch = substr(s, j, 1)
    if(ch == "\n"){ go_shut(); goout = goout "\n"; j++; continue }
    if(escapes && ch == "\\" && substr(s, j + 1, 1) != "" && substr(s, j + 1, 1) != "\n"){
      t = go_esclen(s, j)
      if(GOESC == "Error" && quote == SQ){ go_put("Constant", "str", substr(s, j, t)); j += t; continue }
      go_put(GOESC, GOESCKIND, substr(s, j, t)); j += t; continue }
    if(verbs && ch == "%"){
      if(substr(s, j + 1, 1) == "%"){ go_put("Constant", "str", "%%"); j += 2; continue }
      # that file looks behind a per cent sign for the character before it, and
      # a look behind does not reach over a line end, so one at the head of a
      # line is no verb at all
      if(j > 1 && substr(s, j - 1, 1) != "\n" && (t = go_fmtlen(s, j)) > 0){
        go_put("Special", "fmt", substr(s, j, t)); j += t; continue } }
    go_put("Constant", "str", ch); j++
    if(ch == quote) break }
  return j }

# go(): one go block, as the spans that colour it.
function go(s,   n, i, j, k, ch, w, prev, t){
  goout = ""; gocls = ""; goitem = ""
  n = length(s); i = 1
  while(i <= n){
    ch = substr(s, i, 1)
    prev = (i > 1 ? substr(s, i - 1, 1) : "")

    if(ch == "\n"){ go_shut(); goout = goout "\n"; i++; continue }

    if(ch == "/" && substr(s, i + 1, 1) == "/"){
      j = go_pkgcomment(s, go_eol(s, i), 1)
      if(j == 0) j = go_eol(s, i)
      go_ctext("line", substr(s, i, j - i)); i = j; continue }
    if(ch == "/" && substr(s, i + 1, 1) == "*"){
      j = findat(s, "*/", i + 2)
      if(j == 0){ go_ctext("block", substr(s, i)); i = n + 1; continue }
      k = go_pkgcomment(s, j + 2, 0)
      if(k > 0) j = k - 2
      go_ctext("block", substr(s, i, j - i + 2)); i = j + 2; continue }

    if(ch == "\""){ i = go_string(s, i, n, "\"", 1, 1); continue }
    if(ch == "`"){ i = go_string(s, i, n, "`", 0, 1); continue }
    if(ch == SQ){ i = go_string(s, i, n, SQ, 1, 0); continue }

    if((ch ~ /[0-9.]/) && !go_kwchar(prev) && (t = go_number(s, i, n, prev)) > 0){
      go_put("Constant", "num", substr(s, i, t - i)); i = t; continue }

    if(ch ~ /[A-Za-z_]/){
      j = i
      while(go_kwchar(substr(s, j, 1))) j++
      w = substr(s, i, j - i)
      if(w in GODECL)       go_put(go_decl(s, j) ? "Statement" : "", "stmt", w)
      else if(w in GOSTMT)  go_put("Statement", "stmt", w)
      else if(w in GOTYPE)  go_put("Type", "type", w)
      else if(w in GOFUNC)  go_put("Identifier", "func", w)
      else if(w in GOCONST) go_put("Constant", "const", w)
      else                  go_put("", "", w)
      i = j; continue }

    go_put("", "", ch); i++ }
  go_shut()
  return bs_link(goout) }

# --- ruby ---------------------------------------------------------------------
# The colours in a ruby block are the ones the blocks already in the tree carry.
# Those came out of vim, so what is reimplemented below is syntax/ruby.vim in the
# mode it comes in, where it pairs every end with the word it closes: the end of
# a def, a class or a module is the colour of that word and the end of a do or an
# if is the colour of a statement, which is why rb_open() keeps a stack of them.
# The rest is that file too: the delimiters of a string are not the colour of
# what it holds, an interpolation is read as code, a slash opens a regular
# expression only where a value may begin, and a heredoc holds the lines after
# the one it is written on.
#
# rb_shut(), rb_put(): the output, one span at a time, the way cl_put() does it
# for clips - a span ends where the colour ends or the item does.
function rb_shut(){ if(rbcls != ""){ rbout = rbout "</span>"; rbcls = "" } rbitem = "" }

function rb_put(cls, item, txt){
  if(cls != rbcls || item != rbitem){
    rb_shut()
    if(cls != "") rbout = rbout "<span class=\"" cls "\">"
    rbcls = cls; rbitem = item }
  rbout = rbout codeesc(txt) }

# rb_lines(): the same, for text that runs over a line end.
function rb_lines(cls, item, txt,   p){
